/**
 * The event registry — every Phase-0 domain event with its payload schema.
 *
 * `docs/01 §5` gives the naming rule and the core catalogue; each module spec §7
 * lists its own. Registration is enforced: `OutboxWriter.emit()` looks the type
 * up here and refuses an unregistered one, and `docs/09 §4` round-trips every
 * registered event through its schema in CI.
 *
 * Payloads are deliberately **thin**. An event says *what happened*, carrying
 * only the identifiers and the few facts a consumer needs to decide whether to
 * act; the consumer then reads the current state through the owning module's
 * service. Fat events go stale in the queue and become a second, divergent copy
 * of the record — and for clinical data, `docs/07 §3` is explicit: "invalidate
 * keys, do not push payloads into the cache … the refetch is the authority."
 */
import { z } from 'zod';

export interface EventDefinition {
  readonly type: string;
  readonly aggregate: string;
  readonly module: string;
  readonly description: string;
  readonly schema: z.ZodType;
  readonly schemaVersion: number;
  /** True when any payload field is PHI-classified (drives redaction). */
  readonly containsPhi: boolean;
  /**
   * Retention in days for the *event* row after publication. docs/03 §Outbox:
   * "purged 7 d after publish" is the default; a few compliance-relevant facts
   * are kept longer because they are evidence.
   */
  readonly retentionDays: number;
}

const uuid = z.string().uuid();
const iso = z.string().datetime({ offset: true });

/**
 * Money in an event payload is a DECIMAL STRING, never a number.
 *
 * `Money` is bigint minor units in code (`primitives/money.ts`), and an event is
 * JSON: a number would go through IEEE-754 on the way out and back, so
 * ₹1,234.55 could arrive as 1234.5499999999999. A consumer posting that to a
 * ledger would be wrong by a paisa, every time, in a way nobody notices until a
 * reconciliation fails.
 */
const money = z.string().regex(/^-?\d+(\.\d{1,2})?$/, 'money must be a decimal string, e.g. "1234.55"');

function ev(
  type: string,
  aggregate: string,
  module: string,
  description: string,
  schema: z.ZodType,
  opts: { containsPhi?: boolean; retentionDays?: number; schemaVersion?: number } = {},
): EventDefinition {
  return {
    type,
    aggregate,
    module,
    description,
    schema,
    schemaVersion: opts.schemaVersion ?? 1,
    containsPhi: opts.containsPhi ?? false,
    retentionDays: opts.retentionDays ?? 7,
  };
}

