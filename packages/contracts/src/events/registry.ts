const eventsByType = new Map(EVENT_REGISTRY.map((d) => [d.type, d]));

if (eventsByType.size !== EVENT_REGISTRY.length) {
  const seen = new Set<string>();
  const dupes = EVENT_REGISTRY.map((d) => d.type).filter((t) => (seen.has(t) ? true : (seen.add(t), false)));
  throw new Error(`Duplicate event types in the registry: ${[...new Set(dupes)].join(', ')}`);
}

// docs/01 §5: naming is `<aggregate>.<past-tense-fact>`. Enforce the shape so a
// typo like `admin.userCreated` cannot reach the outbox.
for (const d of EVENT_REGISTRY) {
  if (!/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/.test(d.type)) {
    throw new Error(
      `Event type "${d.type}" does not match <aggregate>.<past-tense-fact> in lower_snake segments (docs/01 §5).`,
    );
  }
}

export function getEventDefinition(type: string): EventDefinition | undefined {
  return eventsByType.get(type);
}

/** Producers call this before writing to the outbox (docs/09 §4). */
export function assertRegisteredEvent(type: string): EventDefinition {
  const def = eventsByType.get(type);
  if (!def) {
    throw new Error(
      `Unregistered event type "${type}". Add it to packages/contracts/src/events/registry.ts — ` +
        `an unregistered event has no schema, so no consumer can validate it (docs/09 §4).`,
    );
  }
  return def;
}

export const EVENT_TYPES: readonly string[] = Object.freeze(EVENT_REGISTRY.map((d) => d.type));

export function eventsForModule(moduleId: string): readonly EventDefinition[] {
  return EVENT_REGISTRY.filter((d) => d.module === moduleId);
}

/** Event types whose payload is PHI-bearing and must be redacted before logging. */
export const PHI_EVENT_TYPES: readonly string[] = Object.freeze(
  EVENT_REGISTRY.filter((d) => d.containsPhi).map((d) => d.type),
);
