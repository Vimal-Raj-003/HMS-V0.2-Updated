// ─────────────────────────────────────────────────────────────────────────────
// Phase 4 — Pharmacy, Stores & Supply Chain
//
// Three things govern what a payload carries here, and the first two are the
// ones this phase gets wrong most easily:
//
//  1. **Money is a decimal string.** Every value below that is a price, a rate,
//     a landed cost or a variance goes through `money`. A purchase order worth
//     ₹1,234.55 that arrives as 1234.5499999999999 posts a wrong accrual, and
//     nobody notices until a reconciliation fails months later.
//
//  2. **Quantity is a decimal string too, and it is *base* quantity.** The
//     database refuses a quantity whose UoM is absent from the item's
//     conversion ladder (`inventory.enforce_qty_uom`), so a consumer that adds
//     `qtyBase` values is adding the same unit every time. A payload carrying
//     "2" with no unit is the bug `phase-04 §Constraints` names: "Any
//     arithmetic mixing UoMs without conversion is a bug."
//
//  3. **A dispense names a patient, so it is PHI.** So does a consignment
//     usage, a patient consumption entry and the H1/NDPS register. Those are
//     marked `containsPhi` and the relay redacts them before logging
//     (`docs/04 §4`). `inventory.stock.moved` deliberately does **not** carry
//     `patientId` — the ledger row has it, the consumer reads it if entitled,
//     and the movement feed stays out of the PHI redaction path.
//
// Retention: a GST record is kept eight years (`docs/04 §1`), an NDPS register
// entry and an implant traceability fact effectively forever, and ordinary
// stock housekeeping is operational chatter. The `retentionDays` below say so
// rather than defaulting to the seven-day outbox purge.
// ─────────────────────────────────────────────────────────────────────────────

