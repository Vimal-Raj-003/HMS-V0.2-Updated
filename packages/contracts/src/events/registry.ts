// ─────────────────────────────────────────────────────────────────────────────
// Phase 2 — OPD Clinical Core
//
// From the §7 Domain Events section of OP-002, OP-007, EN-029, NC-003 and
// OP-019.
//
// Retention here is not uniform, and the split is deliberate:
//
//   • 2555 days (7 years) for anything that is a *clinical or medico-legal fact*
//     — the consultation, the diagnosis, the allergy, the prescription, the
//     order, the alert that fired and what the clinician did about it, the
//     charge intent that becomes a tax invoice, the destruction approval.
//   • 400 days for workflow signals that only ever drive a screen: a consult
//     starting, a token-level Rx hold, a recheck request.
//   • 90 days for `vitals.recorded`, which fires several times per patient per
//     day and exists only to invalidate caches and wake a worklist. The
//     observation itself lives in `clinical.vitals` for ten years; the *event
//     row* has no evidentiary value once it has been consumed. The abnormal and
//     critical variants are the opposite — they are the proof that a clinician
//     was told — and keep the full 2555.
//
// A quantity is a decimal string for the same reason money is: `2.5` survives
// JSON, but a consumer that multiplies an IEEE-754 quantity by an IEEE-754 unit
// price and posts the result to a ledger is wrong by a paisa, silently.
// ─────────────────────────────────────────────────────────────────────────────

const quantity = z
  .string()
  .regex(/^\d+(\.\d{1,4})?$/, 'quantity must be a decimal string, e.g. "1" or "2.5"');

const diagnosisCode = z.object({
  code: z.string(),
  system: z.enum(['icd10', 'icd11', 'snomed']),
  rank: z.enum(['primary', 'secondary']),
  certainty: z.enum(['provisional', 'confirmed', 'rule_out', 'chronic']),
});

const orderCategory = z.enum([
  'lab',
  'radiology',
  'procedure',
  'nursing',
  'referral',
  'admission',
  'diet',
  'physio',
  'other',
]);
const orderPriority = z.enum(['routine', 'urgent', 'stat']);

/** What a downstream fulfiller needs to start work without reading back. */
