#!/usr/bin/env node
/**
 * Rewrites a freshly generated Prisma migration so the high-write tables are
 * declaratively partitioned by month.
 *
 * Prisma cannot express `PARTITION BY RANGE`, and `docs/03 §Migrations` sanctions
 * exactly this: "hand-written SQL in `prisma/migrations/*​/migration.sql` for RLS,
 * partitions, indexes, triggers, materialised views (Prisma cannot express them)".
 *
 * Kept as a script rather than a one-off edit because the base migration gets
 * regenerated whenever the Phase-0 schema changes, and re-deriving the edit by
 * hand each time is how a partition silently goes missing — which would not fail
 * any test until the table was already 40 million rows deep.
 *
 * Usage:  node scripts/apply-partitioning.mjs <path-to-migration.sql>
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** table fragment → [partition key, human name, why it is partitioned] */
const PARTITIONED = new Map([
  ['core"."audit_log', ['occurred_at', 'core.audit_log', '8–15 M rows/day at 2000 beds (EN-024 §13)']],
  ['core"."outbox_events', ['occurred_at', 'core.outbox_events', '~500 k rows/day, purged 7 days after publish (docs/07 §1.3)']],
  ['core"."sessions', ['created_at', 'core.sessions', '180-day online retention per CERT-In (EN-007 §5)']],
  ['core"."login_audit', ['occurred_at', 'core.login_audit', '180-day online retention per CERT-In (EN-024 §3.3)']],
  ['core"."org_cross_branch_access_log', ['occurred_at', 'core.org_cross_branch_access_log', '7-year DPDP disclosure log (EN-041 §4)']],
]);

const HEADER = `-- ─────────────────────────────────────────────────────────────────────────────
-- Vim's HMS — Phase 0 platform schema
--
-- Generated by \`prisma migrate dev --create-only\`, then post-processed by
-- \`packages/db/scripts/apply-partitioning.mjs\` BEFORE first application to add
-- declarative monthly partitioning to the five high-write tables
-- (docs/03 §Table rules, docs/07 §4).
--
-- Applied in order after this file:
--   ..._partitions_and_indexes  — initial partitions, partial and trigram indexes
--   ..._rls_policies            — row-level security on every application table
--   ..._audit_guards            — append-only enforcement and the hash chain
--   ..._grants                  — least-privilege role grants
--
-- ROLLBACK: see the block at the foot of this file.
-- ─────────────────────────────────────────────────────────────────────────────

`;

const FOOTER = `

-- ─────────────────────────────────────────────────────────────────────────────
-- ROLLBACK:
--   This is the initial migration; rolling back means dropping the four schemas
--   it creates. Safe ONLY before any tenant data exists.
--
--   DROP SCHEMA IF EXISTS "analytics" CASCADE;
--   DROP SCHEMA IF EXISTS "integration" CASCADE;
--   DROP SCHEMA IF EXISTS "mdm" CASCADE;
--   DROP SCHEMA IF EXISTS "core" CASCADE;
--
--   \`ext\` is NOT dropped: it is owned by infrastructure, not by migrations.
--
--   Once a tenant is live this migration is not reversible, and per docs/09 §16
--   that fact belongs in the release note rather than being discovered during an
--   incident. Every release after Phase 0 uses expand/contract (docs/10 §6) so
--   rollback never requires a database restore.
-- ─────────────────────────────────────────────────────────────────────────────
`;

const target = process.argv[2];
if (!target) {
  console.error('usage: node scripts/apply-partitioning.mjs <path-to-migration.sql>');
  process.exit(1);
}

let sql = readFileSync(target, 'utf8');

if (sql.includes('PARTITION BY RANGE')) {
  console.log('already partitioned — nothing to do');
  process.exit(0);
}

let patched = 0;
for (const [fragment, [key, name, why]] of PARTITIONED) {
  const escaped = fragment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`(CREATE TABLE "${escaped}" \\((?:[^;]*?)\\n\\))(;)`, 's');
  const m = re.exec(sql);
  if (!m) {
    console.error(`FAIL: could not locate CREATE TABLE for ${name}.`);
    console.error('The schema changed shape. Fix this script rather than hand-editing the migration.');
    process.exit(1);
  }
  const replacement =
    `${m[1]}\nPARTITION BY RANGE ("${key}")${m[2]}\n` +
    `-- Partitioned monthly: ${why}.\n` +
    `-- A month must be droppable in < 1 s (docs/07 §4), which DELETE can never be.\n`;
  sql = sql.slice(0, m.index) + replacement + sql.slice(m.index + m[0].length);
  patched += 1;
}

writeFileSync(target, HEADER + sql + FOOTER);
console.log(`patched ${patched}/${PARTITIONED.size} tables to PARTITION BY RANGE; added header and ROLLBACK block`);
