-- ═════════════════════════════════════════════════════════════════════════════
-- §A. THE CHANGE LOG: MONTHLY PARTITIONS, APPEND ONLY
--
-- `mdm.tariff_change_log` is the audit of record for pricing. RC-003 §5 keeps it
-- 8 years for GST and contract audit, and a hospital repricing a few thousand
-- services a year fills it steadily. Partitioned monthly so the eventual purge
-- is a DETACH rather than a table rewrite, and so a query for "what changed in
-- March" reads one partition.
--
-- Prisma cannot express declarative partitioning, so the table it created is
-- replaced here. Doing this in the same migration that created it is safe
-- precisely because nothing has written to it yet.
-- ═════════════════════════════════════════════════════════════════════════════
DROP TABLE IF EXISTS "mdm"."tariff_change_log";

CREATE TABLE "mdm"."tariff_change_log" (
  "id"          UUID NOT NULL,
  "hospital_id" UUID NOT NULL,
  "version_id"  UUID NOT NULL,
  "item_id"     UUID,
  "package_id"  UUID,
  "service_id"  UUID,
  "field"       VARCHAR(64) NOT NULL,
  "old_value"   TEXT,
  "new_value"   TEXT,
  "changed_by"  UUID NOT NULL,
  "changed_at"  TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
