-- §A. MONTHLY PARTITIONS
--
-- `core.ensure_month_partition()` (defined in ..._partitions_and_indexes,
-- extended in ..._rls_policies) creates one month, enables RLS on it, attaches
-- the tenant policies, grants and storage parameters — so a partition the worker
-- creates in 2031 is protected exactly like one created here.
--
-- ── Why every partition key in this phase is `timestamptz(3)` ────────────────
--
-- A partitioned table's primary key must contain its partitioning column, so
-- `clinical.vitals`, `clinical.cdss_alert_events`, `clinical.cdss_scores` and
-- `core.mobile_sync_log` all have a composite key `(id, <timestamp>)`. Phase 1
-- learned twice what that costs at `timestamptz(6)`: PostgreSQL stores
-- microseconds, JavaScript's `Date` holds milliseconds, so a key read into an
-- application object and written back matches **zero rows** — silently, because
-- an UPDATE that affects nothing is not an error. D-31 answers that with "a
-- timestamp used as part of a key is round-tripped as text, never through a JS
-- `Date`", which is correct and which every future caller must remember.
--
-- These four columns remove the trap instead of documenting it. At millisecond
-- precision the round trip through a `Date` is exact, so the rule and the type
-- agree rather than the rule having to compensate for the type. Nothing here is
-- measured to the microsecond: a nurse's cuff reading, a CDSS fire, a NEWS2
-- computation and a mobile sync receipt are all human-scale events, and
-- `cdss_alert_events.latency_ms` carries the sub-second figure that actually
-- matters. Ordering within a millisecond comes from the UUIDv7 in `id`, which is
-- time-ordered by construction.
--
-- Premake the current month, three ahead and one behind: a back-dated catch-up
-- entry from the downtime protocol (docs/01 §7) must have somewhere to land.
-- ═════════════════════════════════════════════════════════════════════════════
DO $$
DECLARE
  v_tables text[][] := ARRAY[
    ['clinical', 'vitals'],
    ['clinical', 'cdss_alert_events'],
    ['clinical', 'cdss_scores'],
    ['core', 'mobile_sync_log']
  ];
  i int;
  m int;
BEGIN
  FOR i IN 1 .. array_length(v_tables, 1) LOOP
    FOR m IN -1 .. 3 LOOP
      PERFORM core.ensure_month_partition(
        v_tables[i][1],
        v_tables[i][2],
        (date_trunc('month', now()) + (m || ' month')::interval)::date
      );
    END LOOP;
  END LOOP;
END
$$;

-- ── DEFAULT partitions ───────────────────────────────────────────────────────
-- Without one, an INSERT whose timestamp falls outside every declared range
-- fails. For `clinical.vitals` that failure would stop a nurse charting a
-- critical observation; for `cdss_alert_events` it would roll back the very
-- prescription transaction whose safety check it records, which is the worst
-- possible way for a safety system to fail. A default partition turns a missed
-- maintenance run from an outage into a monitored anomaly (a non-empty default
-- partition is alertable, never normal).
DO $$
DECLARE
  v_tables text[][] := ARRAY[
    ['clinical', 'vitals'],
    ['clinical', 'cdss_alert_events'],
    ['clinical', 'cdss_scores'],
    ['core', 'mobile_sync_log']
  ];
  i int;
  v_schema     text;
  v_table      text;
  v_default    text;
  v_qualified  text;
  v_using      text;
  v_has_branch boolean;
BEGIN
  FOR i IN 1 .. array_length(v_tables, 1) LOOP
    v_schema  := v_tables[i][1];
    v_table   := v_tables[i][2];
    v_default := v_table || '_default';
    v_qualified := format('%I.%I', v_schema, v_default);

    IF NOT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = v_schema AND c.relname = v_default
    ) THEN
      EXECUTE format('CREATE TABLE %s PARTITION OF %I.%I DEFAULT', v_qualified, v_schema, v_table);
    END IF;

    SELECT count(*) FILTER (WHERE column_name = 'branch_id') > 0
    INTO v_has_branch
    FROM information_schema.columns
    WHERE table_schema = v_schema AND table_name = v_table;

    v_using := 'hospital_id = ANY (core.accessible_hospital_ids())';
    IF v_has_branch THEN
      v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
    END IF;

    EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', v_qualified);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %s', v_qualified);
    EXECUTE format('CREATE POLICY tenant_isolation ON %s FOR ALL TO hms_app USING (%s) WITH CHECK (%s)',
                   v_qualified, v_using, v_using);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_ro ON %s', v_qualified);
    EXECUTE format('CREATE POLICY tenant_isolation_ro ON %s FOR SELECT TO hms_readonly USING (%s)',
                   v_qualified, v_using);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %s TO hms_app', v_qualified);
    EXECUTE format('GRANT SELECT ON %s TO hms_readonly', v_qualified);

    EXECUTE format(
      'COMMENT ON TABLE %s IS %L',
      v_qualified,
      'Safety net only. A non-empty default partition is an alertable anomaly (docs/07 §6), never a normal state.'
    );
  END LOOP;
END
$$;


