-- §B. ROW-LEVEL SECURITY
--
-- Phase 1 added five schemas and had to widen `core.v_rls_coverage`,
-- `core.v_rls_open_policies` and `core.v_grant_coverage` before writing a single
-- policy, because a table in a schema the views do not know about is unmonitored
-- rather than safe.
--
-- **Phase 2 adds no schema.** Every one of its 58 tables lands in `mdm`,
-- `clinical`, `billing` or `core`, all four of which the three views already
-- cover. That is not something to assume, so B.1 asserts it in SQL before the
-- generator runs: if a future edit moves a table into `analytics` or a new
-- bounded-context schema, this migration fails at that point rather than
-- shipping 58 invisible tables behind a monitor that reports zero.
-- ═════════════════════════════════════════════════════════════════════════════

-- ── 1. assert the coverage monitors reach every schema this migration wrote ──
DO $$
DECLARE
  -- The schemas `core.v_rls_coverage` was widened to in the Phase-1 migration.
  v_covered  text[] := ARRAY['core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration'];
  -- The application schemas the datasource declares (prisma/schema/schema.prisma).
  -- `analytics` is declared and empty; if a phase ever puts a table there without
  -- widening the views, this is where it is caught. Infrastructure schemas —
  -- `ext`, `cron`, `partman`, `public` — are owned by ADR-0008 and are not
  -- application data, so they are deliberately outside the question.
  v_declared text[] := ARRAY['core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration', 'analytics'];
  v_missing  text;
  v_schema   text;
BEGIN
  SELECT string_agg(DISTINCT n.nspname, ', ')
  INTO v_missing
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE c.relkind IN ('r', 'p')
    AND c.relispartition = false
    AND c.relname NOT LIKE '\_prisma%'
    AND n.nspname = ANY (v_declared)
    AND NOT (n.nspname = ANY (v_covered));

  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION
      'Phase 2 created tables in schema(s) % which core.v_rls_coverage does not monitor. Widen the three coverage views BEFORE generating policies, exactly as the Phase-1 migration did — otherwise the integration suite will go on reporting zero unprotected tables while these sit open.',
      v_missing;
  END IF;

  -- And the views themselves must still list all eight. A CREATE OR REPLACE in a
  -- later migration that narrowed them would be caught here.
  FOREACH v_schema IN ARRAY v_covered LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_views v
      WHERE v.schemaname = 'core' AND v.viewname = 'v_rls_coverage'
        AND v.definition LIKE '%''' || v_schema || '''%'
    ) THEN
      RAISE EXCEPTION 'core.v_rls_coverage no longer covers schema %', v_schema;
    END IF;
  END LOOP;
END
$$;

-- ── 2. the policy generator ──────────────────────────────────────────────────
-- Identical in shape to the Phase-0 and Phase-1 generators, and narrowed the
-- same way to tables that do not already carry a `tenant_isolation` policy, so
-- it cannot clobber the explicit tenant-key exceptions or the ten
-- global-catalogue policies.
--
-- Phase 2 has both kinds of table. Most carry `hospital_id NOT NULL`. Seven do
-- not: `cdss_rules`, `cdss_rule_versions`, `cdss_override_reason_sets`,
-- `cdss_override_reasons`, `cdss_kb_releases`, `cdss_kb_interactions`,
-- `cdss_kb_dose_rules` and `cdss_allergy_cross_map` are nullable, because a null
-- hospital is content the product ships (the local formulary, the penicillin
-- cross-sensitivity class) and a value is content a tenant authored or licensed.
-- The generator's mixed-table branch handles that correctly: a tenant reads both
-- and may write only its own.
--
-- `clinical.cdss_safety_floor` has no `hospital_id` at all and is handled
-- separately in B.3, because the generated `USING (false)` would make it
-- unreadable and an unreadable safety floor is a safety floor that does not
-- fire.
DO $$
DECLARE
  r                record;
  v_has_hospital   boolean;
  v_hospital_null  boolean;
  v_has_branch     boolean;
  v_using          text;
  v_check          text;
  v_count          int := 0;
  v_unprotected    text;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration')
      AND c.relkind IN ('r', 'p')
      AND c.relispartition = false
      AND c.relname NOT LIKE '\_prisma%'
      AND c.relname <> 'cdss_safety_floor'
      AND NOT EXISTS (
        SELECT 1 FROM pg_policy p
        WHERE p.polrelid = c.oid AND p.polname = 'tenant_isolation'
      )
    ORDER BY n.nspname, c.relname
  LOOP
    SELECT
      count(*) FILTER (WHERE column_name = 'hospital_id') > 0,
      bool_or(column_name = 'hospital_id' AND is_nullable = 'YES'),
      count(*) FILTER (WHERE column_name = 'branch_id') > 0
    INTO v_has_hospital, v_hospital_null, v_has_branch
    FROM information_schema.columns
    WHERE table_schema = r.schema_name AND table_name = r.table_name;

    EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', r.schema_name, r.table_name);

    IF v_has_hospital AND NOT v_hospital_null THEN
      v_using := 'hospital_id = ANY (core.accessible_hospital_ids())';
      IF v_has_branch THEN
        v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;
      v_check := v_using;

    ELSIF v_has_hospital AND v_hospital_null THEN
      v_using := '(hospital_id IS NULL OR hospital_id = ANY (core.accessible_hospital_ids()))';
      IF v_has_branch THEN
        v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;
      v_check := 'hospital_id = ANY (core.accessible_hospital_ids())';
      IF v_has_branch THEN
        v_check := v_check || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;

    ELSE
      -- Deliberately NOT `USING (true)`: a table with no tenant column that
      -- nobody classified fails loudly at first use rather than leaking.
      v_using := 'false';
      v_check := 'false';
    END IF;

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I.%I FOR ALL TO hms_app USING (%s) WITH CHECK (%s)',
      r.schema_name, r.table_name, v_using, v_check
    );

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_ro ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation_ro ON %I.%I FOR SELECT TO hms_readonly USING (%s)',
      r.schema_name, r.table_name, v_using
    );

    v_count := v_count + 1;
  END LOOP;

  RAISE NOTICE 'Row-level security enabled with tenant policies on % new tables', v_count;
END
$$;

-- ── 3. the safety floor: readable by every tenant, writable by none ─────────
-- Same predicate as the Phase-0 global catalogues: not `USING (true)`, so a
-- session that never established a tenant context still reads nothing, but
-- `WITH CHECK (false)` so no tenant can insert a floor row of its own —
-- and, more importantly, §D revokes UPDATE and DELETE so no tenant can remove
-- one either. The floor is code-owned. There is no supported path by which a
-- running system stops enforcing it.
DO $$
DECLARE
  v_using text := 'cardinality(core.accessible_hospital_ids()) > 0';
BEGIN
  ALTER TABLE clinical.cdss_safety_floor ENABLE ROW LEVEL SECURITY;

  DROP POLICY IF EXISTS tenant_isolation ON clinical.cdss_safety_floor;
  EXECUTE format(
    'CREATE POLICY tenant_isolation ON clinical.cdss_safety_floor FOR ALL TO hms_app USING (%s) WITH CHECK (false)',
    v_using
  );

  DROP POLICY IF EXISTS tenant_isolation_ro ON clinical.cdss_safety_floor;
  EXECUTE format(
    'CREATE POLICY tenant_isolation_ro ON clinical.cdss_safety_floor FOR SELECT TO hms_readonly USING (%s)',
    v_using
  );
END
$$;

-- ── 4. assert, in the migration itself, what the integration suite asserts ──
-- A migration that half-applied its own security is worse than one that failed,
-- because it looks finished.
DO $$
DECLARE
  v_unprotected text;
BEGIN
  SELECT string_agg(format('%s.%s', schema_name, table_name), ', ' ORDER BY schema_name, table_name)
  INTO v_unprotected
  FROM core.v_rls_coverage
  WHERE NOT rls_enabled OR NOT has_tenant_policy OR (is_tenant_scoped AND NOT has_write_check);

  IF v_unprotected IS NOT NULL THEN
    RAISE EXCEPTION 'Phase 2 migration left table(s) without complete row-level security: %', v_unprotected;
  END IF;

  -- `core.v_rls_open_policies` must still be exactly the two Phase-0 catalogues.
  SELECT string_agg(DISTINCT table_name, ', ' ORDER BY table_name)
  INTO v_unprotected
  FROM core.v_rls_open_policies
  WHERE table_name NOT IN ('permissions', 'setting_definitions');

  IF v_unprotected IS NOT NULL THEN
    RAISE EXCEPTION 'Phase 2 migration introduced an unrestricted read policy on: %', v_unprotected;
  END IF;
END
$$;


