-- ── C.6 the hard-stop floor that has nothing to switch off ──────────────────
--
-- `phase-02` exit gate 2: "Prescribe a drug the patient is allergic to → hard
-- stop; **prove in a test that no configuration flag can disable it**."
-- D-9: "Allergy and contraindicated-interaction hard-stops never degrade when
-- CDSS is offline." docs/04 §7 lists the whole floor.
--
-- The way to make that provable is to leave nothing to prove. A flag can be
-- audited, guarded, permission-gated — and eventually flipped, in an incident,
-- at 3 a.m., by somebody with the right role and the wrong information. So the
-- floor is not a flag. It is a table with no state:
--
--   * no `hospital_id`     → no tenant row can shadow or replace a floor entry
--   * no `active`/`status` → there is no value that means "off"
--   * no `effective_to`    → it cannot be aged out
--   * no suppression       → EN-029 §5: "Suppression never applies to hard-stops"
--   * no INSERT/UPDATE/DELETE for `hms_app` (§D) → it cannot be emptied either
--
-- The assertion below is the part that keeps it true. It reads
-- `information_schema` and fails the migration if the table has acquired a
-- boolean, a status-shaped column or a tenant key. A later phase that adds
-- `cdss_safety_floor.enabled` will not ship; it will fail here, loudly, with
-- this message. That is a much stronger guarantee than a test somebody can mark
-- `skip`.

DO $$
DECLARE
  v_offending text;
BEGIN
  SELECT string_agg(column_name || ' ' || data_type, ', ' ORDER BY column_name)
  INTO v_offending
  FROM information_schema.columns
  WHERE table_schema = 'clinical'
    AND table_name = 'cdss_safety_floor'
    AND (
      -- Any switch, by any of the names a switch is given.
      column_name ~ '^(active|enabled|disabled|is_active|is_enabled|suspended|status|state|effective_to|valid_to|expires_at|disabled_at|retired_at|suppressed|suppression|override_allowed|bypass|waiver)$'
      -- Any tenant key: a per-hospital floor is not a floor.
      OR column_name IN ('hospital_id', 'branch_id', 'group_id', 'org_id')
      -- Any boolean other than the one documentation column.
      OR (data_type = 'boolean' AND column_name <> 'degrades_offline')
    );

  IF v_offending IS NOT NULL THEN
    RAISE EXCEPTION
      'clinical.cdss_safety_floor has acquired column(s) that could disable or scope a product-level hard stop: %. docs/04 §7 and phase-02 exit gate 2 require that no configuration can turn these off — the absence of the column IS the guarantee. If a floor family genuinely needs to change, change the seeded rows in a migration reviewed by the Medical Superintendent (docs/04 §7 Change control), not by adding a switch.',
      v_offending;
  END IF;
END
$$;

