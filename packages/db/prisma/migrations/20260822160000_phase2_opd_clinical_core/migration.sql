-- ═════════════════════════════════════════════════════════════════════════════
-- §D. GRANTS AND APPEND-ONLY ENFORCEMENT
--
-- Phase 1's `ALTER DEFAULT PRIVILEGES` covers everything `hms_migrator` creates
-- in `patient`, `clinical`, `queue`, `engage` and `billing` from that point on,
-- so most of these 58 tables arrived already granted. `core` and `mdm` were
-- covered by the Phase-0 defaults. The loop below is the belt to that braces: it
-- grants only tables that hold no grant yet, for the same reason as before —
-- `GRANT ... ON ALL TABLES` would silently re-grant UPDATE and DELETE on the
-- append-only tables and undo every guarantee below it.
-- ═════════════════════════════════════════════════════════════════════════════
DO $$
DECLARE
  r record;
  v_count int := 0;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name, c.oid
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration')
      AND c.relkind IN ('r', 'p')
      AND c.relispartition = false
      AND c.relname NOT LIKE '\_prisma%'
      AND NOT has_table_privilege('hms_app', c.oid, 'SELECT')
  LOOP
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I.%I TO hms_app', r.schema_name, r.table_name);
    EXECUTE format('GRANT SELECT ON %I.%I TO hms_readonly', r.schema_name, r.table_name);
    v_count := v_count + 1;
  END LOOP;
  RAISE NOTICE 'Granted application DML on % previously ungranted table(s)', v_count;
END
$$;

-- ── 1. the safety floor: readable, and nothing else ─────────────────────────
--    This is the grant half of the guarantee the schema half describes. The
--    floor has no column that means "off"; this makes sure it also has no row
--    that can be removed. `hms_app` may read it and may do nothing else to it,
--    which means the only way a running system stops enforcing a floor family is
--    a migration written by the schema owner and reviewed as a clinical-logic
--    change (docs/04 §7 Change control). That is the intended cost.
REVOKE INSERT, UPDATE, DELETE ON clinical.cdss_safety_floor FROM hms_app;

-- Same treatment for the knowledge base a licensed loader populates: the
-- application evaluates against it and never edits it, so a compromised service
-- cannot invent a severity grading or widen a dose ceiling at runtime. (Same
-- reasoning as `core.permissions` and `mdm.mdm_concepts` in Phase 0.)
REVOKE INSERT, UPDATE, DELETE ON clinical.cdss_kb_interactions FROM hms_app;
REVOKE INSERT, UPDATE, DELETE ON clinical.cdss_kb_dose_rules FROM hms_app;

-- ── 2. append-only evidence: INSERT and SELECT only ─────────────────────────
--    A fired alert, the clinician's response to it, an encounter transition and
--    an order status change are all statements about something that happened.
--    Editing one is not a correction, it is a falsification — the correction is
--    another row.
--
--    `cdss_alert_events` is the one that matters most: EN-029 §5 requires alert
--    rows to be immutable and to carry `rule_version_id` + `snapshot_digest`, so
--    that a medico-legal review three years later can reconstruct exactly what
--    the prescriber was shown. That is also why the clinician's response is a
--    separate `cdss_alert_actions` row rather than an `outcome` column somebody
