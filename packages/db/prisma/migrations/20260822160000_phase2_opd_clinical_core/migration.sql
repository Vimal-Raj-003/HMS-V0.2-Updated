-- `clinical.documents.current_version` / `current_status` are a projection, and
-- a projection a caller maintains is a projection that drifts.
CREATE OR REPLACE FUNCTION clinical.sync_document_head()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_document uuid := COALESCE(NEW.document_id, OLD.document_id);
BEGIN
  UPDATE clinical.documents d
  SET current_version = head.version,
      current_status  = head.status,
      updated_at      = now()
  FROM (
    SELECT version, status
    FROM clinical.document_versions
    WHERE document_id = v_document
    ORDER BY version DESC
    LIMIT 1
  ) AS head
  WHERE d.id = v_document
    AND (d.current_version IS DISTINCT FROM head.version OR d.current_status IS DISTINCT FROM head.status);

  RETURN NULL;
END;
$$;

