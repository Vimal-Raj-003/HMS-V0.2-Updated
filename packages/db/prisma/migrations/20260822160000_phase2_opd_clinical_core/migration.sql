-- The block itself. A destruction run may not even be *approved* while its set
-- contains a medico-legal record or one under a legal hold — checked at approval
-- rather than only at execution, because an approved run is a run somebody will
-- execute, and the point of failing early is that a human is still looking.
CREATE OR REPLACE FUNCTION clinical.enforce_mrd_destruction_protection()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_protected text;
BEGIN
  IF NEW.status NOT IN ('approved', 'executed') THEN
    RETURN NEW;
  END IF;

  -- Two *distinct* approvers. This lives here and not in the CHECK beside it
  -- because a CHECK constraint may not contain a subquery, and de-duplicating an
  -- array without one is not worth the expression.
  IF (SELECT count(DISTINCT a) FROM unnest(NEW.approved_by) AS a) < 2 THEN
    RAISE EXCEPTION
      'MRD destruction run % needs two distinct approvers (NC-003 §5); % supplied were not distinct',
      NEW.id, cardinality(NEW.approved_by)
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT string_agg(
           format('%s (%s)', COALESCE(r.mrd_no, r.id::text),
                  CASE WHEN r.is_medico_legal THEN 'medico-legal' ELSE 'legal hold to ' || r.legal_hold_until END),
           ', ' ORDER BY r.id)
  INTO v_protected
  FROM clinical.mrd_records r
  WHERE r.id = ANY (NEW.record_ids)
    AND (r.is_medico_legal OR (r.legal_hold_until IS NOT NULL AND r.legal_hold_until >= current_date));

  IF v_protected IS NOT NULL THEN
    RAISE EXCEPTION
      'MRD destruction run % includes protected record(s): %. NC-003 §5: a medico-legal record is never destroyed, and a record under legal hold is not destroyed until the hold lapses. Remove them from the run.',
      NEW.id, v_protected
      USING ERRCODE = 'restrict_violation';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION clinical.enforce_mrd_destruction_protection IS
  'NC-003 §5 and phase-02 §2.7: the medico-legal flag blocks destruction. Enforced at approval as well as execution, because an approved run is one somebody will execute and the moment to fail is while a human is still reading the screen.';

