-- The two halves a CHECK cannot express: the free-text minimum lives on the
-- reason, and the countersignature requirement lives on the floor.
CREATE OR REPLACE FUNCTION clinical.enforce_cdss_override()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_requires_text boolean;
  v_min_length    int;
  v_label         text;
  v_floor_key     text;
  v_countersign   text;
BEGIN
  IF NEW.kind <> 'overridden' THEN
    RETURN NEW;
  END IF;

  SELECT requires_free_text, min_free_text_length, label
  INTO v_requires_text, v_min_length, v_label
  FROM clinical.cdss_override_reasons
  WHERE id = NEW.override_reason_id;

  IF v_requires_text AND length(btrim(COALESCE(NEW.override_note, ''))) < v_min_length THEN
    RAISE EXCEPTION
      'CDSS override reason "%" requires at least % characters of explanation (EN-029 §5); % supplied',
      v_label, v_min_length, length(btrim(COALESCE(NEW.override_note, '')))
      USING ERRCODE = 'check_violation';
  END IF;

  -- EN-029 §5: a floor family "may be acknowledged with countersign, never
  -- silently bypassed". Where the floor entry names a countersigning role, the
  -- countersignature is part of the override, not a follow-up task.
  SELECT e.safety_floor_key INTO v_floor_key
  FROM clinical.cdss_alert_events e
  WHERE e.id = NEW.alert_event_id AND e.fired_at = NEW.alert_fired_at;

  IF v_floor_key IS NOT NULL THEN
    SELECT countersign_role INTO v_countersign
    FROM clinical.cdss_safety_floor WHERE key = v_floor_key;

    IF v_countersign IS NULL THEN
      RAISE EXCEPTION
        'Safety floor "%" admits no override at all (docs/04 §7). The order must change.',
        v_floor_key
        USING ERRCODE = 'restrict_violation';
    END IF;

    IF NEW.countersigned_by IS NULL THEN
      RAISE EXCEPTION
        'Safety floor "%" may be acknowledged only with a % countersignature (EN-029 §5), never silently bypassed',
        v_floor_key, v_countersign
        USING ERRCODE = 'restrict_violation';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION clinical.enforce_cdss_override IS
  'EN-029 §5, the two halves a CHECK cannot reach: the free-text minimum declared on the chosen reason, and the countersignature a safety-floor family demands. A floor entry with no countersign_role admits no override at all — the prescriber changes the order.';

