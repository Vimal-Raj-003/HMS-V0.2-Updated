-- ── C.5 the append-only clinical document ───────────────────────────────────
--
-- CLAUDE.md §3: "Append-only clinical record. Clinical documents are versioned;
-- an 'edit' creates a new version with reason; finalised documents are immutable
-- and digitally signed (hash chain)." docs/04 §7 repeats it. `phase-02` exit
-- gate 4 tests it: "Amend a signed note → new version, old version intact,
-- reason captured, audit chain valid."
--
-- Four mechanisms, because each closes a different hole:
--
--   1. The hash is computed by the database from the content, so a caller cannot
--      present a digest that does not describe what it stored.
--   2. `prev_sha256` is checked against the actual preceding version, so the
--      chain cannot be re-linked to hide a removed version.
--   3. A trigger refuses any UPDATE that would change content, hash, signature
--      or identity once the version has left `draft`, and refuses every DELETE.
--   4. §D revokes DELETE from `hms_app` entirely, so even a bug that bypassed
--      the trigger's exception path has nothing to bypass it with.
--
-- The two columns an UPDATE may still touch after `final` are
-- `superseded_by_version` and `superseded_at` — plus the single status
-- transition `final → amended` or `final → cancelled` that accompanies them.
-- Nothing else. A "cancelled" version keeps its content: retracting a document
-- is a clinical act, and destroying its text would remove the evidence of what
-- was retracted.

ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_version_positive CHECK (version >= 1);
-- An amendment with no reason is an overwrite wearing a version number.
ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_amendment_reason
  CHECK (version = 1 OR amendment_reason IS NOT NULL);
-- Version 1 starts the chain; every later version continues one.
ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_chain_root
  CHECK ((version = 1) = (prev_sha256 IS NULL));
-- A finalised version is a signed version. An unsigned "final" document is the
-- thing the whole hash chain exists to make impossible.
ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_signed_when_final
  CHECK (
    status = 'draft'
    OR (signed_by IS NOT NULL AND signed_at IS NOT NULL AND sign_method IS NOT NULL)
  );
ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_cancel_reason
  CHECK (status <> 'cancelled' OR cancelled_reason IS NOT NULL);
ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_superseded_pairing
  CHECK ((superseded_by_version IS NULL) = (superseded_at IS NULL));
ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_superseded_forward
  CHECK (superseded_by_version IS NULL OR superseded_by_version > version);
ALTER TABLE clinical.document_versions
  ADD CONSTRAINT document_versions_sha_shape
  CHECK (content_sha256 ~ '^[0-9a-f]{64}$');

-- The sealer. Computes the digest, links the chain, and refuses a version that
-- claims a predecessor it does not have.
CREATE OR REPLACE FUNCTION clinical.seal_document_version()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_prev_hash   text;
  v_prev_exists boolean;
BEGIN
  -- 1. The digest is ours, not the caller's. `content::text` is jsonb's
  --    canonical rendering — key order normalised, whitespace removed — so the
  --    same document always produces the same hash regardless of how the client
  --    happened to serialise it.
  NEW.content_sha256 := encode(sha256(convert_to(NEW.content::text, 'UTF8')), 'hex');

  IF TG_OP = 'INSERT' THEN
    IF NEW.version > 1 THEN
      SELECT content_sha256, true
      INTO v_prev_hash, v_prev_exists
      FROM clinical.document_versions
      WHERE document_id = NEW.document_id AND version = NEW.version - 1;

      IF NOT COALESCE(v_prev_exists, false) THEN
        RAISE EXCEPTION
          'clinical.document_versions: version % of document % has no version % to chain to — versions are contiguous by construction',
          NEW.version, NEW.document_id, NEW.version - 1
          USING ERRCODE = 'foreign_key_violation';
      END IF;

      -- 2. The link is ours too. A caller that supplied the wrong predecessor
      --    hash is either confused or trying to detach a version; either way the
      --    database knows the right answer and uses it.
      NEW.prev_sha256 := v_prev_hash;
    ELSE
      NEW.prev_sha256 := NULL;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION clinical.seal_document_version IS
  'Computes content_sha256 from the content and links prev_sha256 to the preceding version. Both are taken from the database rather than accepted from the caller: a hash chain whose links the writer supplies proves only that the writer can compute sha256.';

DROP TRIGGER IF EXISTS trg_document_versions_seal ON clinical.document_versions;
CREATE TRIGGER trg_document_versions_seal
  BEFORE INSERT OR UPDATE ON clinical.document_versions
  FOR EACH ROW EXECUTE FUNCTION clinical.seal_document_version();

-- The immutability guard.
CREATE OR REPLACE FUNCTION clinical.enforce_document_version_immutability()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION
      'clinical.document_versions is append-only: version % of document % cannot be deleted. A retraction is a status of cancelled with a reason; a correction is a new version.',
      OLD.version, OLD.document_id
      USING ERRCODE = 'restrict_violation';
  END IF;

  -- A draft is a draft. Everything about it may change until it is signed.
  IF OLD.status = 'draft' THEN
    RETURN NEW;
  END IF;

  IF NEW.content        IS DISTINCT FROM OLD.content
     OR NEW.content_text   IS DISTINCT FROM OLD.content_text
     OR NEW.content_sha256 IS DISTINCT FROM OLD.content_sha256
     OR NEW.prev_sha256    IS DISTINCT FROM OLD.prev_sha256
     OR NEW.version        IS DISTINCT FROM OLD.version
     OR NEW.document_id    IS DISTINCT FROM OLD.document_id
     OR NEW.hospital_id    IS DISTINCT FROM OLD.hospital_id
     OR NEW.signed_by      IS DISTINCT FROM OLD.signed_by
     OR NEW.signed_at      IS DISTINCT FROM OLD.signed_at
     OR NEW.sign_method    IS DISTINCT FROM OLD.sign_method
     OR NEW.signer_registration_no IS DISTINCT FROM OLD.signer_registration_no
     OR NEW.amendment_reason IS DISTINCT FROM OLD.amendment_reason
     OR NEW.created_at     IS DISTINCT FROM OLD.created_at
     OR NEW.created_by     IS DISTINCT FROM OLD.created_by
  THEN
    RAISE EXCEPTION
      'clinical.document_versions: version % of document % is % and immutable. Amend it by writing version % with a reason; the original stays.',
      OLD.version, OLD.document_id, OLD.status, OLD.version + 1
      USING ERRCODE = 'restrict_violation';
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status
     AND NOT (OLD.status = 'final' AND NEW.status IN ('amended', 'cancelled'))
  THEN
    RAISE EXCEPTION
      'clinical.document_versions: % cannot become % (only final → amended and final → cancelled are permitted after signing)',
      OLD.status, NEW.status
      USING ERRCODE = 'restrict_violation';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION clinical.enforce_document_version_immutability IS
