-- The DPCO hard block itself. It spans two tables, so it is a trigger rather
-- than a CHECK: a brand may not be *activated* at an MRP above the ceiling
-- notified for its formulation. Drafts may hold any figure — the point is to
-- refuse the activation, which is the moment the price becomes chargeable.
CREATE OR REPLACE FUNCTION mdm.enforce_dpco_ceiling()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_ceiling    numeric(14, 2);
  v_generic    text;
  v_unit_price numeric(14, 4);
BEGIN
  IF NEW.status <> 'active' OR NEW.mrp IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT d.dpco_ceiling_price, d.generic_name
  INTO v_ceiling, v_generic
  FROM mdm.mdm_drugs d
  WHERE d.record_key = NEW.drug_key
    AND d.status = 'active'
    AND d.dpco_scheduled = true
    AND d.effective_from <= now()
    AND (d.effective_to IS NULL OR d.effective_to > now())
  ORDER BY d.effective_from DESC
  LIMIT 1;

  -- Per unit, not per pack. A pack size of NULL means the MRP *is* the unit
  -- price (a single vial, an inhaler), which is the safe reading: it compares
  -- the whole figure against the ceiling rather than waving it through.
  v_unit_price := NEW.mrp / COALESCE(NULLIF(NEW.pack_size, 0), 1);

  IF v_ceiling IS NOT NULL AND v_unit_price > v_ceiling THEN
    RAISE EXCEPTION
      'DPCO 2013: brand "%" cannot be activated at MRP % for a pack of % — that is % per unit and the notified ceiling for % is %',
      NEW.brand_name, NEW.mrp, COALESCE(NEW.pack_size, 1), round(v_unit_price, 4), v_generic, v_ceiling
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_drug_brands_dpco_ceiling ON mdm.mdm_drug_brands;
CREATE TRIGGER trg_drug_brands_dpco_ceiling
  BEFORE INSERT OR UPDATE ON mdm.mdm_drug_brands
  FOR EACH ROW EXECUTE FUNCTION mdm.enforce_dpco_ceiling();

