-- ── the tunable table cannot be used to route around the floor ──────────────
-- A tenant is free to author rules in a floor family — a soft-stop for a mild
-- intolerance is a legitimate allergy-family rule, and it should be tunable.
-- What must not happen is a floor check being *implemented* as an ordinary rule
-- and then disabled. `cdss_rules.enforces_floor_key` is the declaration that a
-- rule is such an implementation, and this trigger is what it costs to make it.
CREATE OR REPLACE FUNCTION clinical.enforce_cdss_safety_floor()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_floor_key text;
BEGIN
  IF TG_TABLE_NAME = 'cdss_rules' THEN
    IF NEW.enforces_floor_key IS NULL THEN
      RETURN NEW;
    END IF;

    IF NEW.status IN ('disabled', 'shadow', 'retired') THEN
      RAISE EXCEPTION
        'clinical.cdss_rules "%" enforces safety floor "%" and cannot be set to %. docs/04 §7: this family can never be configured away. Detach it from the floor only by removing the check from the product, in a migration.',
        NEW.key, NEW.enforces_floor_key, NEW.status
        USING ERRCODE = 'restrict_violation';
    END IF;

    IF NEW.disabled_at IS NOT NULL THEN
      RAISE EXCEPTION
        'clinical.cdss_rules "%" enforces safety floor "%" and cannot be emergency-disabled (EN-029 §3.4.5 applies to tunable rules only)',
        NEW.key, NEW.enforces_floor_key
        USING ERRCODE = 'restrict_violation';
    END IF;

    RETURN NEW;
  END IF;

  -- cdss_rule_versions
  SELECT r.enforces_floor_key INTO v_floor_key
  FROM clinical.cdss_rules r WHERE r.id = NEW.rule_id;

  IF v_floor_key IS NULL THEN
    RETURN NEW;
  END IF;

  IF NEW.interruption <> 'hard_stop' THEN
    RAISE EXCEPTION
      'clinical.cdss_rule_versions: version % enforces safety floor "%" and must be hard_stop, not %. Downgrading a floor family is exactly what docs/04 §7 forbids.',
      NEW.version, v_floor_key, NEW.interruption
      USING ERRCODE = 'restrict_violation';
  END IF;

  IF NEW.suppression IS NOT NULL AND NEW.suppression <> '{}'::jsonb THEN
    RAISE EXCEPTION
      'clinical.cdss_rule_versions: version % enforces safety floor "%" and may carry no suppression policy (EN-029 §5: "Suppression never applies to hard-stops or critical values")',
      NEW.version, v_floor_key
      USING ERRCODE = 'restrict_violation';
  END IF;

  IF NEW.effective_to IS NOT NULL THEN
    RAISE EXCEPTION
      'clinical.cdss_rule_versions: version % enforces safety floor "%" and may not be given an end date',
      NEW.version, v_floor_key
      USING ERRCODE = 'restrict_violation';
  END IF;

  RETURN NEW;
END;
$$;

