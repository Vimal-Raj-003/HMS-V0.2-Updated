-- ── 4. the retention role ───────────────────────────────────────────────────
--    Note what is NOT in this list. `clinical.vitals`, `clinical.cdss_alert_events`
--    and `clinical.cdss_scores` are partitioned, but they are clinical records
--    with ten-year statutory retention (EN-029 §4: alert events "retained 10
--    years — medico-legal, matches the clinical record"), so no scheduled job
--    may remove them. Their partitions are detached by `hms_migrator` under an
--    explicit release procedure (docs/13), never by a sweeper.
--
--    Two tables here are genuinely operational: the CDSS snapshot cache, which
--    EN-029 §4 gives 90 days and which exists only to reproduce an alert, and
--    the mobile sync ledger, which holds no PHI by construction.
GRANT USAGE ON SCHEMA clinical TO hms_retention;
GRANT SELECT, DELETE ON clinical.cdss_patient_snapshots TO hms_retention;
GRANT SELECT, DELETE ON core.mobile_sync_log            TO hms_retention;

DO $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      ('clinical', 'cdss_patient_snapshots'),
      ('core', 'mobile_sync_log')
    ) AS t(schema_name, table_name)
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS retention_all_tenants ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY retention_all_tenants ON %I.%I FOR ALL TO hms_retention USING (true) WITH CHECK (true)',
      r.schema_name, r.table_name
    );
  END LOOP;
END
$$;

-- ── 5. assert the grants match the intent ───────────────────────────────────
-- `core.v_grant_coverage` exists so that "readonly can write" and "the app can
-- update the audit log" are caught by a query rather than by an incident. The
-- same check belongs in the migration that could have introduced them.
DO $$
DECLARE
  v_bad text;
BEGIN
  SELECT string_agg(format('%s.%s', table_schema, table_name), ', ' ORDER BY table_schema, table_name)
  INTO v_bad
  FROM core.v_grant_coverage
  WHERE readonly_has_write;

  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'Phase 2 granted write privileges to hms_readonly on: %', v_bad;
  END IF;

  -- And the floor is read-only, which is the assertion this whole phase turns on.
  IF has_table_privilege('hms_app', 'clinical.cdss_safety_floor', 'INSERT')
     OR has_table_privilege('hms_app', 'clinical.cdss_safety_floor', 'UPDATE')
     OR has_table_privilege('hms_app', 'clinical.cdss_safety_floor', 'DELETE')
  THEN
    RAISE EXCEPTION
      'clinical.cdss_safety_floor is writable by hms_app. docs/04 §7 and phase-02 exit gate 2 require that the application cannot add, alter or remove a product-level hard stop.';
  END IF;

  IF (SELECT count(*) FROM clinical.cdss_safety_floor) < 6 THEN
    RAISE EXCEPTION 'clinical.cdss_safety_floor is missing entries: docs/04 §7 lists six families and % are present',
      (SELECT count(*) FROM clinical.cdss_safety_floor);
  END IF;
END
$$;

