-- The chain verifier an assessor asks for, and the integration suite asserts.
-- Recomputes every digest from its own content and re-walks every link.
CREATE OR REPLACE FUNCTION clinical.verify_document_chain(p_document_id uuid)
RETURNS TABLE (
  version         int,
  status          text,
  hash_matches    boolean,
  link_matches    boolean
)
LANGUAGE sql
STABLE
AS $$
  SELECT
    v.version,
    v.status::text,
    v.content_sha256 = encode(sha256(convert_to(v.content::text, 'UTF8')), 'hex') AS hash_matches,
    COALESCE(
      v.prev_sha256 IS NOT DISTINCT FROM lag(v.content_sha256) OVER (ORDER BY v.version),
      false
    ) AS link_matches
  FROM clinical.document_versions v
  WHERE v.document_id = p_document_id
  ORDER BY v.version;
$$;

COMMENT ON FUNCTION clinical.verify_document_chain IS
  'One row per version with its digest and link re-verified from scratch. `hash_matches = false` means the content was changed under the hash; `link_matches = false` means a version was removed or re-parented. Both should be impossible; the point of a verifier is not to trust that.';

GRANT EXECUTE ON FUNCTION clinical.verify_document_chain(uuid) TO hms_app, hms_readonly;

