CREATE TRIGGER trg_invoice_match_compute
  BEFORE INSERT OR UPDATE ON inventory.pur_invoice_match_lines
  FOR EACH ROW EXECUTE FUNCTION inventory.compute_invoice_match();

-- The invoice's own status follows its lines: matched only if every line is.
CREATE OR REPLACE FUNCTION inventory.roll_up_invoice_match()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_invoice_id uuid := coalesce(NEW.invoice_id, OLD.invoice_id);
  v_worst      "inventory"."PurMatchStatus";
BEGIN
  SELECT l.status INTO v_worst
  FROM inventory.pur_invoice_match_lines l
  WHERE l.invoice_id = v_invoice_id
  ORDER BY CASE l.status
             WHEN 'no_grn'         THEN 1
             WHEN 'qty_mismatch'   THEN 2
             WHEN 'price_mismatch' THEN 3
             WHEN 'tax_mismatch'   THEN 4
             WHEN 'pending'        THEN 5
             ELSE 9
           END
  LIMIT 1;

  UPDATE inventory.pur_vendor_invoices i
  SET match_status = coalesce(v_worst, 'pending'), updated_at = now()
  WHERE i.id = v_invoice_id
    -- A human decision (`disputed`, `approved_for_payment`, `posted`) is not
    -- overwritten by a recomputation.
    AND i.match_status NOT IN ('disputed', 'approved_for_payment', 'posted')
    AND i.match_status IS DISTINCT FROM coalesce(v_worst, 'pending');

  RETURN NULL;
END;
$$;

