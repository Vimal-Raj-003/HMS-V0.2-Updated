-- ── C.4 the controlled-drug register ────────────────────────────────────────
--
-- `docs/04 §1` (CDSCO / Drugs & Cosmetics Act; NDPS Act) requires a Schedule
-- H/H1 register, a Schedule X register and "an **NDPS narcotic register with
-- dual authorisation and physical stock reconciliation**". `phase-04` exit gate
-- 4: "Narcotic issue requires two users; the register balances against physical
-- count; a deliberate mismatch raises an alert and **cannot be silently
-- adjusted**."
--
-- Five mechanisms, and each replaces a rule somebody would otherwise have to
-- remember:
--
--   append-only        a statutory register that can be edited is not a
--                      register. UPDATE and DELETE both raise, and §D revokes
--                      both privileges as well.
--   dual authorisation for `ndps`, a second authoriser is mandatory and must
--                      not be the first. Two signatures from one person are one
--                      signature.
--   running balance    `balance_after_base` is computed from the previous row
--                      by the database under an advisory lock on the register.
--                      Supplied by the caller, two concurrent entries produce
--                      two rows both claiming the same balance, and the page
--                      the inspector reads does not add up.
--   in XOR out         exactly one of `qty_in_base` / `qty_out_base` is
--                      non-zero. A row that is both is not a transaction.
--   patient identified an NDPS or Schedule X dispense names the patient and the
--                      prescriber's registration number. That is what the
--                      register is *for*.
--
-- ── And the limits that are actually real ──────────────────────────────────
--
-- `pharmacy.controlled_substance_limits` exists because the obvious design —
-- a `max_course_days` on every controlled drug — encodes a rule that does not
-- exist. The NDPS regime for Essential Narcotic Drugs (morphine, fentanyl,
-- methadone, oxycodone, codeine/ethylmorphine, hydrocodone; S.O. 1181(E) of
-- 5 May 2015) lives in Chapters VA and VB of the NDPS Rules 1985, inserted by
-- G.S.R. 359(E) of 5 May 2015, and **it contains no maximum duration and no
-- maximum quantity per patient**. Rule 52U caps what the institution may hold
-- against its Form 3J estimate and rule 52T's Explanation lets even that be
-- exceeded with a recorded justification. Rule 52G(i) requires the prescription
-- to state total quantity, daily dose and period of consumption — it delegates
-- the period to the prescriber rather than capping it.
--
-- What *is* a hard number is **NDPS Rules 1985, rule 66(2)**: 100 dosage units
-- of a psychotropic substance for personal medical use, or 300 where the
-- prescriber has specifically prescribed for long-term personal medical use.
-- That binds Schedule X and the psychotropic Schedule H1 drugs, not the ENDs.
--
-- So the table separates `basis = 'statutory'` from `basis = 'policy'` and
-- refuses to let a hospital relax the first. India's morphine consumption fell
-- ~92 % under the pre-2015 licensing regime and the 2014 amendment exists to
-- undo that; a fabricated seven-day ceiling in a product default would quietly
-- rebuild it in every hospital that installed this.
-- ═════════════════════════════════════════════════════════════════════════════

ALTER TABLE pharmacy.controlled_drug_register
  ADD CONSTRAINT controlled_drug_register_in_xor_out
  CHECK (
    (qty_in_base > 0 AND qty_out_base = 0)
    OR (qty_out_base > 0 AND qty_in_base = 0)
  );

ALTER TABLE pharmacy.controlled_drug_register
  ADD CONSTRAINT controlled_drug_register_dual_auth
  CHECK (
    register_type <> 'ndps'
    OR (second_auth_user_id IS NOT NULL AND second_auth_user_id <> first_auth_user_id)
  );

-- A dispense from the NDPS or Schedule X register names the patient and the
-- prescriber's registration. `docs/04 §1`: "H1 register with prescriber
-- details"; the D&C Rules require the same for X.
ALTER TABLE pharmacy.controlled_drug_register
  ADD CONSTRAINT controlled_drug_register_dispense_identified
  CHECK (
    txn_type <> 'dispense'
    OR (
      (patient_id IS NOT NULL OR (patient_name IS NOT NULL AND length(btrim(patient_name)) > 0))
      AND prescriber_name IS NOT NULL
      AND (register_type = 'schedule_h1' OR (prescriber_reg_no IS NOT NULL AND length(btrim(prescriber_reg_no)) > 0))
    )
  );

