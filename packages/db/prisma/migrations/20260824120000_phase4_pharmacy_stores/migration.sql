-- ─────────────────────────────────────────────────────────────────────────────
-- Vim's HMS — Phase 4: pharmacy, stores and supply chain
--
-- `docs/prompts/phase-04-pharmacy-stores.md` in tables. 110 of them, in five
-- schemas, **three of which are new** — and that is the dangerous part of this
-- migration, for the reason the Phase-1 migration learned the hard way and §B
-- repeats: a table in a schema the RLS coverage monitor does not know about is
-- unmonitored rather than safe.
--
--   mdm            6  EN-027's supply-chain masters. Units of measure with a
--                     dimension, the item category tree, manufacturers, HSN/SAC
--                     codes, the GST rate history behind them, and the NPPA
--                     DPCO ceiling history. `mdm_drugs` and `mdm_drug_brands`
--                     already exist (Phase 2); what arrives here is the tax and
--                     measurement identity a *stock* item needs.
--   inventory NEW 74  NC-006, NC-005, NC-007, NC-008 and NC-021. The item
--                     master and its per-item conversion ladder, the vendor
--                     master and its rate contracts, stores and bins and
--                     temperature zones, batches and serials/UDI, **the
--                     append-only stock ledger** and its balance projection,
--                     indents/issues/transfers/returns/adjustments/counts, the
--                     whole purchase-to-pay chain including the 3-way match and
--                     its exception queue, consignment agreements, receipts,
--                     usages and reconciliations, and consumption entries.
--   pharmacy  NEW 15  OP-003. `docs/03 §Schemas` reserves the name: "lab / rad /
--                     **pharmacy** / blood / ot / ip / er … one schema per
--                     bounded context". The Rx queue, dispenses and their lines,
--                     backorders, substitution requests, interventions, sale
--                     returns, **the controlled-drug register**, narcotic
--                     custody checks, expiry decisions, recalls and their
--                     patient traces, counselling checklists, the day close, and
--                     the controlled-substance limit table §C.4 explains.
--   finance   NEW  2  NC-008 §4 puts cost centres in schema `finance`. Phase 9
--                     owns the rest of it (GL, AP, AR); creating the schema now
--                     with two tables is the cheaper mistake, because two tables
--                     both called "the cost centre" is exactly the fork
--                     `docs/03 §Shared platform-owned tables` exists to prevent.
--
-- Generated by `prisma migrate diff --from-url`, then post-processed by
-- `packages/db/scripts/apply-partitioning-phase4.mjs` BEFORE first application
-- to add declarative monthly partitioning to three high-write tables, to strip
-- the thirty-five DropIndex statements Prisma emits for hand-written SQL it
-- cannot represent, and to strip one cosmetic AlterTable. Everything after the
-- Prisma-generated section is hand-written.
--
-- Read the four sections at the foot of this file in this order:
--   §A  monthly partitions, and why all three are pure append this time
--   §B  row-level security — **the coverage views are widened FIRST**, because
--       `inventory`, `pharmacy` and `finance` are new schemas
--   §C  the constraints and triggers that carry the safety guarantees:
--         C.1  the UoM ladder: the database converts, it does not trust
--         C.2  effective-dated prices: never retroactive, never overlapping
--         C.3  **the append-only stock ledger**, its balance projection, and
--              the refusals that make a dispense fail closed
--         C.4  the controlled-drug register: gapless, dual-authorised, balanced
--              by the database — and the Rule 66(2) limits that are real
--         C.5  dispensing: expired, quarantined, and Schedule-H-over-the-counter
--         C.6  goods receipt: batch, expiry, shelf life, and the 3-way match
--         C.7  consignment: reversed, never deleted; never valued as ours
--   §D  least-privilege grants and append-only enforcement
--
-- ── The one rule this whole migration is built around ───────────────────────
--
-- `phase-04 §Constraints`: "**The stock ledger never gets an UPDATE.**
-- Corrections are new compensating entries with reason. Any code that mutates a
-- ledger row fails review." Review is not a mechanism. Four are, and they are
-- deliberately redundant:
--
--   1. `inventory.enforce_ledger_append_only()` raises on UPDATE and on DELETE,
--      unconditionally, on the parent and on every partition.
--   2. §D revokes UPDATE and DELETE on the table from `hms_app`, so a dropped
--      trigger is not enough on its own.
--   3. The partitions are created by `core.ensure_month_partition()`, which
--      grants SELECT and INSERT and nothing else — so next April's partition
--      arrives with the same guarantee rather than inheriting a mistake.
--   4. `inventory.stock_balances` is maintained by an AFTER INSERT trigger on
--      the ledger and by nothing else, so `sum(qty_base) = qty_on_hand` holds by
--      construction. `inventory.verify_stock_integrity()` re-derives it and is
--      what `phase-04` exit gate 6 runs.
--
