-- ── the match verdict ───────────────────────────────────────────────────────
-- Computed from the line's own differences and the hospital's tolerances, in
-- the database, so the exception queue and the buyer's screen cannot disagree.
CREATE OR REPLACE FUNCTION inventory.compute_invoice_match()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_invoice      record;
  v_qty_pct      numeric;
  v_qty_abs      numeric;
  v_price_pct    numeric;
  v_price_abs    numeric;
  v_tax_abs      numeric;
  v_qty_ok       boolean;
  v_price_ok     boolean;
  v_tax_ok       boolean;
BEGIN
  SELECT i.hospital_id, i.branch_id INTO v_invoice
  FROM inventory.pur_vendor_invoices i WHERE i.id = NEW.invoice_id;

  SELECT s.qty_tolerance_pct, s.qty_tolerance_abs_base, s.price_tolerance_pct,
         s.price_tolerance_abs, s.tax_tolerance_abs
    INTO v_qty_pct, v_qty_abs, v_price_pct, v_price_abs, v_tax_abs
  FROM inventory.pur_settings s
  WHERE s.hospital_id = v_invoice.hospital_id
    AND (s.branch_id = v_invoice.branch_id OR s.branch_id IS NULL)
  ORDER BY s.branch_id NULLS LAST
  LIMIT 1;

  -- No settings row means no tolerance, which is the safe default: every
  -- difference becomes an exception a human looks at.
  v_qty_pct   := coalesce(v_qty_pct, 0);
  v_qty_abs   := coalesce(v_qty_abs, 0);
  v_price_pct := coalesce(v_price_pct, 0);
  v_price_abs := coalesce(v_price_abs, 0);
  v_tax_abs   := coalesce(v_tax_abs, 0);

  NEW.qty_diff_base := round(NEW.inv_qty_base - NEW.grn_qty_base, 4);
  NEW.rate_diff     := round(NEW.inv_rate_per_base - coalesce(NEW.po_rate_per_base, NEW.inv_rate_per_base), 4);
  NEW.tax_diff      := round(NEW.inv_tax - NEW.po_tax, 2);

  -- Both bounds must hold. A percentage alone waves through a large absolute
  -- difference on a large line; an absolute alone is meaningless across items
  -- that differ by three orders of magnitude in price.
  v_qty_ok := abs(NEW.qty_diff_base) <= v_qty_abs
              AND (NEW.grn_qty_base = 0
                   OR abs(NEW.qty_diff_base) <= abs(NEW.grn_qty_base) * v_qty_pct / 100);
  v_price_ok := abs(NEW.rate_diff) <= v_price_abs
              AND (coalesce(NEW.po_rate_per_base, 0) = 0
                   OR abs(NEW.rate_diff) <= abs(NEW.po_rate_per_base) * v_price_pct / 100);
  v_tax_ok := abs(NEW.tax_diff) <= v_tax_abs;

  IF NEW.grn_line_id IS NULL THEN
    NEW.status := 'no_grn';
  ELSIF NOT v_qty_ok THEN
    NEW.status := 'qty_mismatch';
  ELSIF NOT v_price_ok THEN
    NEW.status := 'price_mismatch';
  ELSIF NOT v_tax_ok THEN
    NEW.status := 'tax_mismatch';
  ELSE
    NEW.status := 'matched';
  END IF;

  NEW.within_tolerance := (NEW.status = 'matched')
                          AND (NEW.qty_diff_base <> 0 OR NEW.rate_diff <> 0 OR NEW.tax_diff <> 0);

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION inventory.compute_invoice_match IS
  'The three-way verdict, computed in the database from the line''s own differences and the hospital''s tolerances. Stored rather than queried so the exception queue and the buyer''s screen cannot disagree, and so "why did this pass" is answerable months later. A missing pur_settings row means zero tolerance — every difference becomes an exception, which is the safe default.';

