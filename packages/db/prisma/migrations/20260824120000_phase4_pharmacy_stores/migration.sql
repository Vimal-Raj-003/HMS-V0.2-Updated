-- ═════════════════════════════════════════════════════════════════════════════
-- §D. GRANTS AND APPEND-ONLY ENFORCEMENT
--
-- The `ALTER DEFAULT PRIVILEGES` in §B.2 covers everything `hms_migrator`
-- creates in `inventory`, `pharmacy` and `finance` **from that point on** —
-- which is not these tables, because Prisma created them before §B ran. `mdm`
-- was already covered by the Phase-0 defaults, so its six new tables arrived
-- granted. The loop below is the belt to those braces: it grants only tables
-- that hold no grant yet, for the same reason as before —
-- `GRANT ... ON ALL TABLES` would silently re-grant UPDATE and DELETE on the
-- append-only tables and undo every guarantee below it.
-- ═════════════════════════════════════════════════════════════════════════════
DO $$
DECLARE
  r record;
  v_count int := 0;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name, c.oid
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'lab', 'rad', 'pharmacy', 'inventory', 'finance', 'queue', 'engage', 'billing', 'integration')
      AND c.relkind IN ('r', 'p')
      AND c.relispartition = false
      AND c.relname NOT LIKE '\_prisma%'
      AND NOT has_table_privilege('hms_app', c.oid, 'SELECT')
  LOOP
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I.%I TO hms_app', r.schema_name, r.table_name);
    EXECUTE format('GRANT SELECT ON %I.%I TO hms_readonly', r.schema_name, r.table_name);
    v_count := v_count + 1;
  END LOOP;
  RAISE NOTICE 'Granted application DML on % previously ungranted table(s)', v_count;
END
$$;

-- ── 1. the two tables this phase exists to protect ──────────────────────────
--
-- `inventory.stock_ledger` — `phase-04 §Constraints`, verbatim: "The stock
-- ledger never gets an UPDATE." The trigger in §C.3 raises; this makes the
-- trigger the second line of defence rather than the only one. A correction is
-- an INSERT, so INSERT stays.
--
-- `pharmacy.controlled_drug_register` — a statutory register under the NDPS Act
-- and the Drugs & Cosmetics Rules. If it could be edited after the fact, the
-- dual-authorisation requirement would reduce to a field somebody fills in
-- later, which is exactly what a witnessed register exists to prevent.
REVOKE UPDATE, DELETE ON inventory.stock_ledger              FROM hms_app;
REVOKE UPDATE, DELETE ON pharmacy.controlled_drug_register   FROM hms_app;

