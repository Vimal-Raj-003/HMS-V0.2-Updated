-- ── the store tree has no cycles ────────────────────────────────────────────
CREATE OR REPLACE FUNCTION inventory.enforce_store_tree()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_cursor uuid := NEW.parent_store_id;
  v_depth  int  := 0;
BEGIN
  WHILE v_cursor IS NOT NULL LOOP
    IF v_cursor = NEW.id THEN
      RAISE EXCEPTION
        'inventory.stores: % would become its own ancestor. A cycle in the store tree makes replenishment non-terminating.',
        NEW.code
        USING ERRCODE = 'check_violation';
    END IF;
    v_depth := v_depth + 1;
    IF v_depth > 20 THEN
      RAISE EXCEPTION 'inventory.stores: store hierarchy deeper than 20 levels under %', NEW.code
        USING ERRCODE = 'check_violation';
    END IF;
    SELECT parent_store_id INTO v_cursor FROM inventory.stores WHERE id = v_cursor;
  END LOOP;
  RETURN NEW;
END;
$$;

