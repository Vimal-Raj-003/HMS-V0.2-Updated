    RAISE EXCEPTION
      'inventory.item_batches: batch % expires on % which is not after its manufacture date %',
      NEW.batch_no, NEW.expiry_date, NEW.mfg_date
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

