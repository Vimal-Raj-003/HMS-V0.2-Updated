-- ── the generic quantity converter ──────────────────────────────────────────
-- Arguments: item column, uom column, qty_entered column, qty_base column.
-- Rounding is to 4 decimal places because that is the scale of every `qty_base`
-- column in this phase; comparing unrounded would fail on a legitimate
-- 1/3-of-a-bottle dose.
CREATE OR REPLACE FUNCTION inventory.enforce_qty_uom()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_row         jsonb := to_jsonb(NEW);
  v_item_col    text  := TG_ARGV[0];
  v_uom_col     text  := TG_ARGV[1];
  v_entered_col text  := TG_ARGV[2];
  v_base_col    text  := TG_ARGV[3];
  v_item_id     uuid;
  v_uom_id      uuid;
  v_entered     numeric;
  v_base        numeric;
  v_factor      numeric;
  v_expected    numeric;
BEGIN
  v_item_id := (v_row ->> v_item_col)::uuid;
  v_uom_id  := (v_row ->> v_uom_col)::uuid;
  v_entered := (v_row ->> v_entered_col)::numeric;
  v_base    := (v_row ->> v_base_col)::numeric;

  -- A null on either side is a different table's problem (a declined dispense
  -- line has no item). Nothing to convert, nothing to check.
  IF v_item_id IS NULL OR v_uom_id IS NULL OR v_entered IS NULL OR v_base IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT u.factor_to_base INTO v_factor
  FROM inventory.item_uoms u
  WHERE u.item_id = v_item_id AND u.uom_id = v_uom_id;

  IF v_factor IS NULL THEN
    RAISE EXCEPTION
      '%.%: uom % is not on the conversion ladder of item %. Add it to inventory.item_uoms before quantities in it can be stored — an unconvertible quantity is not a quantity.',
      TG_TABLE_SCHEMA, TG_TABLE_NAME, v_uom_id, v_item_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  v_expected := round(v_entered * v_factor, 4);

  IF round(v_base, 4) IS DISTINCT FROM v_expected THEN
    RAISE EXCEPTION
      '%.%: % is % in uom %, which is % base units (factor %), but % was stored as %. Convert with the item''s own factor; do not assume 1.',
      TG_TABLE_SCHEMA, TG_TABLE_NAME, v_entered_col, v_entered, v_uom_id,
      v_expected, v_factor, v_base_col, v_base
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION inventory.enforce_qty_uom IS
  'Recomputes qty_base from qty_entered and the item''s own conversion factor and refuses the row when they disagree. One function, attached with per-table column names, to every table in the phase that carries a quantity. phase-04 §Constraints: "Any arithmetic mixing UoMs without conversion is a bug" — this is what makes that unwritable rather than merely forbidden.';

-- Attach it everywhere a quantity is stored with a UoM.
DO $$
DECLARE
  v_targets text[][] := ARRAY[
    ['inventory', 'stock_ledger',          'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'store_indent_lines',    'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'issue_lines',           'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'transfer_lines',        'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'return_to_store_lines', 'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'adjustment_lines',      'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'pur_indent_lines',      'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'pur_rfq_lines',         'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'pur_po_lines',          'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'pur_grn_lines',         'item_id', 'uom_id', 'qty_received_entered', 'qty_received_base'],
    ['inventory', 'pur_return_lines',      'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'csn_receipt_lines',     'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'csn_usages',            'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'csn_return_lines',      'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'cons_entry_lines',      'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'cons_kit_lines',        'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['inventory', 'cons_service_boms',     'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['pharmacy',  'dispense_items',        'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['pharmacy',  'sale_return_items',     'item_id', 'uom_id', 'qty_entered',          'qty_base'],
    ['pharmacy',  'expiry_actions',        'item_id', 'uom_id', 'qty_entered',          'qty_base']
  ];
  i int;
BEGIN
  FOR i IN 1 .. array_length(v_targets, 1) LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%s_qty_uom ON %I.%I',
                   v_targets[i][2], v_targets[i][1], v_targets[i][2]);
    EXECUTE format(
      'CREATE TRIGGER trg_%s_qty_uom BEFORE INSERT OR UPDATE ON %I.%I FOR EACH ROW EXECUTE FUNCTION inventory.enforce_qty_uom(%L, %L, %L, %L)',
      v_targets[i][2], v_targets[i][1], v_targets[i][2],
      v_targets[i][3], v_targets[i][4], v_targets[i][5], v_targets[i][6]
