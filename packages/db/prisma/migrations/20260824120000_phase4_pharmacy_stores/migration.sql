-- ── C.6 goods receipt and the 3-way match ───────────────────────────────────
--
-- `phase-04` exit gate 1 ends with "a quantity mismatch is caught by the match
-- and queued as an exception". Two halves: the GRN must capture enough to make
-- a match possible, and the match must produce a verdict nobody has to
-- recompute.
-- ═════════════════════════════════════════════════════════════════════════════

ALTER TABLE inventory.pur_grn_lines
  ADD CONSTRAINT pur_grn_lines_qty_reconciles
  CHECK (
    qty_received_base >= 0
    AND qty_accepted_base >= 0
    AND qty_rejected_base >= 0
    AND round(qty_accepted_base + qty_rejected_base, 4) = round(qty_received_base, 4)
  );

-- A rejection needs a coded reason, in both directions: a reason attached to a
-- line that rejected nothing is as misleading as a rejection with no reason.
ALTER TABLE inventory.pur_grn_lines
  ADD CONSTRAINT pur_grn_lines_rejection_coded
  CHECK ((qty_rejected_base > 0) = (reject_reason IS NOT NULL));

CREATE OR REPLACE FUNCTION inventory.enforce_grn_line()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_tracking     "inventory"."InvTracking";
  v_item_code    text;
  v_min_shelf    int;
  v_shelf_days   int;
  v_received_at  timestamptz;
  v_store_id     uuid;
  v_vendor_id    uuid;
  v_schedule     "mdm"."MdmDrugSchedule";
  v_lic_to       date;
  v_vendor_name  text;
BEGIN
  SELECT i.tracking, i.code, i.min_shelf_life_days, i.schedule
    INTO v_tracking, v_item_code, v_min_shelf, v_schedule
  FROM inventory.items i WHERE i.id = NEW.item_id;

  IF v_item_code IS NULL THEN
    RAISE EXCEPTION 'inventory.pur_grn_lines: item % does not exist', NEW.item_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  SELECT g.received_at, g.store_id, g.vendor_id INTO v_received_at, v_store_id, v_vendor_id
  FROM inventory.pur_grns g WHERE g.id = NEW.grn_id;

  -- A batch-tracked item must arrive with a batch, and an expiry-tracked one
  -- with an expiry. This is where those two facts enter the system; if they are
  -- allowed to be null here, every downstream guarantee is vacuous.
  IF NEW.qty_accepted_base > 0 AND v_tracking IN ('batch', 'batch_expiry', 'udi')
     AND (NEW.batch_no IS NULL OR length(btrim(NEW.batch_no)) = 0)
  THEN
    RAISE EXCEPTION
      'inventory.pur_grn_lines: % is batch-tracked and this receipt names no batch number.',
      v_item_code
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.qty_accepted_base > 0 AND v_tracking IN ('batch_expiry', 'udi') AND NEW.expiry_date IS NULL THEN
    RAISE EXCEPTION
      'inventory.pur_grn_lines: % is expiry-tracked and this receipt names no expiry date.',
      v_item_code
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.qty_accepted_base > 0 AND NEW.expiry_date IS NOT NULL
     AND NEW.expiry_date <= coalesce(v_received_at, now())::date
  THEN
    RAISE EXCEPTION
      'inventory.pur_grn_lines: batch % of % expires on %, on or before the receipt date. Accepting expired stock into a hospital store is not a partial receipt, it is a rejection.',
      NEW.batch_no, v_item_code, NEW.expiry_date
      USING ERRCODE = 'check_violation';
  END IF;

  -- Minimum shelf life. The item's own rule; the rate contract may be stricter
  -- and the service applies that on top.
  IF NEW.qty_accepted_base > 0 AND NEW.expiry_date IS NOT NULL AND v_min_shelf IS NOT NULL THEN
    v_shelf_days := NEW.expiry_date - coalesce(v_received_at, now())::date;
    IF v_shelf_days < v_min_shelf THEN
      RAISE EXCEPTION
        'inventory.pur_grn_lines: batch % of % has % days of shelf life left and the item requires at least %. Reject it or record a documented waiver on the PO line.',
        NEW.batch_no, v_item_code, v_shelf_days, v_min_shelf
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  -- A scheduled drug may only be bought from a vendor holding a live drug
  -- licence. `docs/04 §1`: drug licence tracking is part of the CDSCO row.
  IF NEW.qty_accepted_base > 0 AND v_schedule IN ('h', 'h1', 'x', 'ndps_narcotic', 'ndps_psychotropic') THEN
    SELECT v.drug_licence_valid_to, v.legal_name INTO v_lic_to, v_vendor_name
    FROM inventory.vnd_vendors v WHERE v.id = v_vendor_id;

    IF v_lic_to IS NULL OR v_lic_to < coalesce(v_received_at, now())::date THEN
      RAISE EXCEPTION
        'inventory.pur_grn_lines: % is a Schedule % drug and vendor % has no drug licence valid on the receipt date.',
        v_item_code, upper(v_schedule::text), coalesce(v_vendor_name, v_vendor_id::text)
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION inventory.enforce_grn_line IS
  'Goods receipt is where a batch and an expiry enter the system, so it is where they are made mandatory. Also refuses stock that is already expired, stock with less shelf life than the item requires, and a scheduled drug from a vendor with no live drug licence.';

