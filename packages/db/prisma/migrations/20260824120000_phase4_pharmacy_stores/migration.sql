-- ── 3. the policy generator ──────────────────────────────────────────────────
-- Identical in shape to the Phase-0 … Phase-3 generators, and narrowed the same
-- way to tables that do not already carry a `tenant_isolation` policy, so it
-- cannot clobber the explicit tenant-key exceptions or the global-catalogue
-- policies.
DO $$
DECLARE
  r                record;
  v_has_hospital   boolean;
  v_hospital_null  boolean;
  v_has_branch     boolean;
  v_using          text;
  v_check          text;
  v_count          int := 0;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'lab', 'rad', 'pharmacy', 'inventory', 'finance', 'queue', 'engage', 'billing', 'integration')
      AND c.relkind IN ('r', 'p')
      AND c.relispartition = false
      AND c.relname NOT LIKE '\_prisma%'
      AND c.relname <> 'cdss_safety_floor'
      AND NOT EXISTS (
        SELECT 1 FROM pg_policy p
        WHERE p.polrelid = c.oid AND p.polname = 'tenant_isolation'
      )
    ORDER BY n.nspname, c.relname
  LOOP
    SELECT
      count(*) FILTER (WHERE column_name = 'hospital_id') > 0,
      bool_or(column_name = 'hospital_id' AND is_nullable = 'YES'),
      count(*) FILTER (WHERE column_name = 'branch_id') > 0
    INTO v_has_hospital, v_hospital_null, v_has_branch
    FROM information_schema.columns
    WHERE table_schema = r.schema_name AND table_name = r.table_name;

    EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', r.schema_name, r.table_name);

    IF v_has_hospital AND NOT v_hospital_null THEN
      v_using := 'hospital_id = ANY (core.accessible_hospital_ids())';
      IF v_has_branch THEN
        v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;
      v_check := v_using;

    ELSIF v_has_hospital AND v_hospital_null THEN
      v_using := '(hospital_id IS NULL OR hospital_id = ANY (core.accessible_hospital_ids()))';
      IF v_has_branch THEN
        v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;
      v_check := 'hospital_id = ANY (core.accessible_hospital_ids())';
      IF v_has_branch THEN
        v_check := v_check || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;

    ELSE
      -- Deliberately NOT `USING (true)`: a table with no tenant column that
      -- nobody classified fails loudly at first use rather than leaking.
      v_using := 'false';
      v_check := 'false';
    END IF;

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I.%I FOR ALL TO hms_app USING (%s) WITH CHECK (%s)',
      r.schema_name, r.table_name, v_using, v_check
    );

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_ro ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation_ro ON %I.%I FOR SELECT TO hms_readonly USING (%s)',
      r.schema_name, r.table_name, v_using
    );

    v_count := v_count + 1;
  END LOOP;

  RAISE NOTICE 'Row-level security enabled with tenant policies on % new tables', v_count;
END
$$;

-- ── 4. assert, in the migration itself, what the integration suite asserts ──
-- A migration that half-applied its own security is worse than one that failed,
-- because it looks finished.
DO $$
DECLARE
  v_unprotected text;
  v_new_tables  bigint;
BEGIN
  SELECT string_agg(format('%s.%s', schema_name, table_name), ', ' ORDER BY schema_name, table_name)
  INTO v_unprotected
  FROM core.v_rls_coverage
  WHERE NOT rls_enabled OR NOT has_tenant_policy OR (is_tenant_scoped AND NOT has_write_check);

  IF v_unprotected IS NOT NULL THEN
    RAISE EXCEPTION 'Phase 4 migration left table(s) without complete row-level security: %', v_unprotected;
  END IF;

  -- And the widened view must actually be seeing the new schemas' tables, not
  -- merely mentioning their names. A widening that matched nothing would pass
  -- the assertion above vacuously.
  SELECT count(*) INTO v_new_tables
  FROM core.v_rls_coverage WHERE schema_name IN ('inventory', 'pharmacy', 'finance');

  IF v_new_tables < 88 THEN
    RAISE EXCEPTION
      'core.v_rls_coverage reports only % table(s) in inventory/pharmacy/finance; Phase 4 created 91. The view is not seeing them, which is the Phase-1 defect all over again.',
      v_new_tables;
  END IF;

  -- `core.v_rls_open_policies` must still be exactly the two Phase-0 catalogues.
  -- The five nullable-tenant masters this phase adds must NOT be in it.
  SELECT string_agg(DISTINCT table_name, ', ' ORDER BY table_name)
  INTO v_unprotected
  FROM core.v_rls_open_policies
  WHERE table_name NOT IN ('permissions', 'setting_definitions');

  IF v_unprotected IS NOT NULL THEN
    RAISE EXCEPTION 'Phase 4 migration introduced an unrestricted read policy on: %', v_unprotected;
  END IF;
END
$$;


