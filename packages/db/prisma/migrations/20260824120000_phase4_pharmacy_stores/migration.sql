-- ── the running balance, computed under a lock ──────────────────────────────
CREATE OR REPLACE FUNCTION pharmacy.compute_register_balance()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_previous   numeric;
  v_expected   numeric;
  v_item_code  text;
  v_narcotic   boolean;
  v_schedule   "mdm"."MdmDrugSchedule";
BEGIN
  -- Serialise entries per (store, register, item, batch). Two pharmacists
  -- issuing from the same safe at the same second would otherwise both read the
  -- same previous balance and both write it forward, and the register would
  -- have two pages numbered the same.
  PERFORM pg_advisory_xact_lock(
    hashtext(NEW.store_id::text || ':' || NEW.register_type::text || ':' ||
             NEW.item_id::text || ':' || coalesce(NEW.batch_id::text, '-'))
  );

  SELECT r.balance_after_base INTO v_previous
  FROM pharmacy.controlled_drug_register r
  WHERE r.store_id = NEW.store_id
    AND r.register_type = NEW.register_type
    AND r.item_id = NEW.item_id
    AND r.batch_id IS NOT DISTINCT FROM NEW.batch_id
  ORDER BY r.entered_at DESC, r.id DESC
  LIMIT 1;

  v_expected := coalesce(v_previous, 0) + NEW.qty_in_base - NEW.qty_out_base;

  IF v_expected < 0 THEN
    SELECT i.code INTO v_item_code FROM inventory.items i WHERE i.id = NEW.item_id;
    RAISE EXCEPTION
      'pharmacy.controlled_drug_register: this entry would take the % balance of % to %. A controlled-drug register cannot go negative — count the safe and post an adjustment with a witnessed remark first.',
      NEW.register_type, coalesce(v_item_code, NEW.item_id::text), v_expected
      USING ERRCODE = 'check_violation';
  END IF;

  -- Computed, never supplied. A caller may pass anything; it is overwritten.
  NEW.balance_after_base := v_expected;

  -- The register must match the drug. An item that is not controlled has no
  -- business in a controlled register, and a controlled one has no business
  -- outside it.
  SELECT i.is_narcotic, i.schedule, i.code INTO v_narcotic, v_schedule, v_item_code
  FROM inventory.items i WHERE i.id = NEW.item_id;

  IF NEW.register_type = 'ndps' AND NOT (coalesce(v_narcotic, false) OR v_schedule IN ('ndps_narcotic', 'ndps_psychotropic')) THEN
    RAISE EXCEPTION
      'pharmacy.controlled_drug_register: % is not a narcotic or psychotropic and does not belong in the NDPS register.',
      coalesce(v_item_code, NEW.item_id::text)
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.register_type = 'schedule_x' AND v_schedule <> 'x' THEN
    RAISE EXCEPTION
      'pharmacy.controlled_drug_register: % is schedule % and does not belong in the Schedule X register.',
      coalesce(v_item_code, NEW.item_id::text), v_schedule
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.register_type = 'schedule_h1' AND v_schedule NOT IN ('h1', 'x', 'ndps_narcotic', 'ndps_psychotropic') THEN
    RAISE EXCEPTION
      'pharmacy.controlled_drug_register: % is schedule % and does not belong in the Schedule H1 register.',
      coalesce(v_item_code, NEW.item_id::text), v_schedule
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION pharmacy.compute_register_balance IS
  'The running balance is derived from the previous entry under a per-register advisory lock, never supplied by the caller. Two pharmacists issuing from one safe in the same second would otherwise write two entries claiming the same balance, and the page an inspector reads would not add up. Also refuses a negative balance and an item in the wrong register.';

DROP TRIGGER IF EXISTS trg_controlled_register_balance ON pharmacy.controlled_drug_register;
CREATE TRIGGER trg_controlled_register_balance
  BEFORE INSERT ON pharmacy.controlled_drug_register
  FOR EACH ROW EXECUTE FUNCTION pharmacy.compute_register_balance();

