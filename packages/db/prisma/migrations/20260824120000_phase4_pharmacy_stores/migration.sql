--
-- ── The global masters, and why they are not an exception ──────────────────
--
-- Five tables here carry a nullable `hospital_id`: `mdm.mdm_uoms`,
-- `mdm.mdm_hsn_codes`, `mdm.mdm_gst_rates`, `mdm.mdm_dpco_ceilings` and
-- `pharmacy.controlled_substance_limits`. A NULL means "shipped with the
-- product" — a millilitre is a millilitre in every hospital, and the NDPS
-- Rule 66(2) dosage-unit ceiling is the same statute for all of them.
--
-- The generator's nullable branch is what they get: readable when
-- `hospital_id IS NULL`, writable only into the session's own tenant. So a
-- hospital reads the shipped rows and can add its own, and can never edit or
-- delete another tenant's — and none of them joins `core.v_rls_open_policies`,
-- which B.4 asserts still contains exactly the two Phase-0 catalogues.
-- ═════════════════════════════════════════════════════════════════════════════

-- ── 1. widen the coverage monitors to the three new schemas ─────────────────
-- Column lists are unchanged; only the schema list moves. `CREATE OR REPLACE
-- VIEW` requires that, which is a useful accident: it means this cannot quietly
-- become a different view.
CREATE OR REPLACE VIEW core.v_rls_coverage AS
SELECT
  n.nspname                                        AS schema_name,
  c.relname                                        AS table_name,
  c.relrowsecurity                                 AS rls_enabled,
  c.relforcerowsecurity                            AS rls_forced,
  count(p.polname) FILTER (WHERE p.polname IS NOT NULL) AS policy_count,
  bool_or(p.polname = 'tenant_isolation')          AS has_tenant_policy,
  bool_or(p.polname = 'tenant_isolation' AND p.polwithcheck IS NOT NULL) AS has_write_check,
  EXISTS (
    SELECT 1 FROM information_schema.columns col
    WHERE col.table_schema = n.nspname AND col.table_name = c.relname
      AND col.column_name = 'hospital_id'
  )                                                AS is_tenant_scoped
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_policy p ON p.polrelid = c.oid
WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'lab', 'rad', 'pharmacy', 'inventory', 'finance', 'queue', 'engage', 'billing', 'integration')
  AND c.relkind IN ('r', 'p')
  AND c.relispartition = false
  AND c.relname NOT LIKE '\_prisma%'
GROUP BY n.nspname, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.oid;

COMMENT ON VIEW core.v_rls_coverage IS
  'One row per application table with its RLS status. `has_tenant_policy` false or `has_write_check` false on a tenant-scoped table is a release-blocking defect (docs/09 §3.1). The schema list must be widened by the migration that adds a schema — a table in a schema this view does not know about is unmonitored, not safe. Widened for `pharmacy`, `inventory` and `finance` in the Phase-4 migration.';

GRANT SELECT ON core.v_rls_coverage TO hms_app, hms_readonly;

CREATE OR REPLACE VIEW core.v_rls_open_policies AS
SELECT
  n.nspname                          AS schema_name,
  c.relname                          AS table_name,
  p.polname                          AS policy_name,
  pg_get_expr(p.polqual, p.polrelid) AS using_expr,
  ARRAY(
    SELECT r.rolname FROM pg_roles r WHERE r.oid = ANY (p.polroles) ORDER BY r.rolname
  )                                  AS granted_to
FROM pg_policy p
JOIN pg_class c ON c.oid = p.polrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'lab', 'rad', 'pharmacy', 'inventory', 'finance', 'queue', 'engage', 'billing', 'integration')
  AND pg_get_expr(p.polqual, p.polrelid) = 'true'
  -- `hms_retention` is excluded by design; `hms_migrator` owns the tables and
  -- bypasses RLS anyway.
  AND EXISTS (
    SELECT 1 FROM pg_roles r
    WHERE r.oid = ANY (p.polroles) AND r.rolname IN ('hms_app', 'hms_readonly')
  );

COMMENT ON VIEW core.v_rls_open_policies IS
  'Policies granting unrestricted reads to a request-serving role (hms_app / hms_readonly). The integration suite asserts this equals exactly {permissions, setting_definitions}; anything else is a cross-tenant leak. hms_retention is deliberately excluded — it spans tenants to archive partitions and holds no privilege on business tables. Widened for `pharmacy`, `inventory` and `finance` in the Phase-4 migration.';

GRANT SELECT ON core.v_rls_open_policies TO hms_app, hms_readonly;

CREATE OR REPLACE VIEW core.v_grant_coverage AS
SELECT
  t.table_schema,
  t.table_name,
  bool_or(g.privilege_type = 'SELECT' AND g.grantee = 'hms_app') AS app_can_select,
  bool_or(g.privilege_type = 'INSERT' AND g.grantee = 'hms_app') AS app_can_insert,
  bool_or(g.privilege_type = 'UPDATE' AND g.grantee = 'hms_app') AS app_can_update,
  bool_or(g.privilege_type = 'DELETE' AND g.grantee = 'hms_app') AS app_can_delete,
  bool_or(g.grantee = 'hms_readonly' AND g.privilege_type <> 'SELECT') AS readonly_has_write
FROM information_schema.tables t
LEFT JOIN information_schema.role_table_grants g
  ON g.table_schema = t.table_schema AND g.table_name = t.table_name
WHERE t.table_schema IN ('core', 'mdm', 'patient', 'clinical', 'lab', 'rad', 'pharmacy', 'inventory', 'finance', 'queue', 'engage', 'billing', 'integration')
  AND t.table_type = 'BASE TABLE'
GROUP BY t.table_schema, t.table_name;

COMMENT ON VIEW core.v_grant_coverage IS
  'Effective privileges per table. `readonly_has_write` true anywhere, `app_can_update` true on core.audit_log, or `app_can_update` true on inventory.stock_ledger, is a release-blocking defect (docs/04 §6, EN-024 §3.4.4, phase-04 §Constraints). Widened for `pharmacy`, `inventory` and `finance` in the Phase-4 migration.';

GRANT SELECT ON core.v_grant_coverage TO hms_app, hms_readonly;

-- The widening is only useful if it actually reached the three new schemas, and
-- a `CREATE OR REPLACE` that silently no-oped would leave the same hole Phase 1
-- had. Assert it before anything depends on it.
DO $$
DECLARE
  v_schema text;
  v_view   text;
BEGIN
  FOREACH v_view IN ARRAY ARRAY['v_rls_coverage', 'v_rls_open_policies', 'v_grant_coverage'] LOOP
    FOREACH v_schema IN ARRAY ARRAY['core', 'mdm', 'patient', 'clinical', 'lab', 'rad', 'pharmacy', 'inventory', 'finance', 'queue', 'engage', 'billing', 'integration'] LOOP
      IF NOT EXISTS (
        SELECT 1 FROM pg_views v
        WHERE v.schemaname = 'core' AND v.viewname = v_view
          AND v.definition LIKE '%''' || v_schema || '''%'
      ) THEN
        RAISE EXCEPTION 'core.% does not cover schema % — widen it before generating policies, not after', v_view, v_schema;
      END IF;
    END LOOP;
  END LOOP;
END
$$;

