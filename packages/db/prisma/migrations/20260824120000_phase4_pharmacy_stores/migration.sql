CREATE TRIGGER trg_invoice_match_rollup
  AFTER INSERT OR UPDATE OR DELETE ON inventory.pur_invoice_match_lines
  FOR EACH ROW EXECUTE FUNCTION inventory.roll_up_invoice_match();

