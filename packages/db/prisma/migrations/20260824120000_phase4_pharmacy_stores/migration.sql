-- §B. ROW-LEVEL SECURITY
--
-- **Phase 4 adds three schemas.** `docs/prompts/phase-03 §Non-negotiables 6`
-- said what that costs and the rule has not changed: "RLS on every new table,
-- asserted inside the migration. If you add a NEW schema, widen the coverage
-- views *before* generating policies, or your tables are invisible to the
-- monitor that exists to catch them."
--
-- Phase 1 is where that lesson was paid for: the three coverage views were
-- written against `('core','mdm','integration')` and ninety-three new tables in
