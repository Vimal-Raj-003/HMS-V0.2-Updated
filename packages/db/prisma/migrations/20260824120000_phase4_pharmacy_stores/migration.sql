-- ── C.3 the append-only stock ledger ────────────────────────────────────────
--
-- `phase-04 §Constraints`, in full: "**The stock ledger never gets an UPDATE.**
-- Corrections are new compensating entries with reason. Any code that mutates a
-- ledger row fails review."
--
-- Everything below exists so that sentence is true of the database rather than
-- of the review process. In order:
--
--   1. the immutability trigger, which raises on UPDATE and DELETE
--      unconditionally (§D also revokes both privileges, so a dropped trigger
--      is not sufficient on its own);
--   2. the sign convention, checked against the movement type, so a receipt
--      cannot be stored as a negative and an issue cannot be stored as a
--      positive;
--   3. the preconditions a movement must satisfy *before* it is recorded —
--      which is where `phase-04` exit gate 3 lives: an expired or quarantined
--      batch cannot leave the shelf, and it is refused here rather than in a
--      service, so it is refused on every path including a bulk import;
--   4. the balance projection, maintained by an AFTER INSERT trigger and by
--      nothing else, which is what makes `sum(ledger) = on_hand` an invariant
--      rather than a hope;
--   5. `inventory.verify_stock_integrity()`, which re-derives the projection
--      from the ledger and returns the disagreements. `phase-04` exit gate 6
--      runs it.
-- ═════════════════════════════════════════════════════════════════════════════

-- ── 1. immutability ─────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION inventory.enforce_ledger_append_only()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION
      'inventory.stock_ledger is append-only: movement % of item % in store % cannot be deleted. Record a compensating entry with movement_type = ''correction'', corrects_ledger_id = %, and a reason.',
      OLD.id, OLD.item_id, OLD.store_id, OLD.id
      USING ERRCODE = 'restrict_violation';
  END IF;

  RAISE EXCEPTION
    'inventory.stock_ledger is append-only: movement % cannot be updated. A stock movement is a statement about something that physically happened; editing it is not a correction, it is a falsification. Record a compensating entry with movement_type = ''correction'', corrects_ledger_id = %, and a reason.',
    OLD.id, OLD.id
    USING ERRCODE = 'restrict_violation';
END;
$$;

COMMENT ON FUNCTION inventory.enforce_ledger_append_only IS
  'phase-04 §Constraints: "The stock ledger never gets an UPDATE." Raises unconditionally on UPDATE and on DELETE, on the partitioned parent and therefore on every partition, present and future. §D additionally revokes both privileges from hms_app, so the guarantee survives this trigger being dropped.';

DROP TRIGGER IF EXISTS trg_stock_ledger_append_only ON inventory.stock_ledger;
CREATE TRIGGER trg_stock_ledger_append_only
  BEFORE UPDATE OR DELETE ON inventory.stock_ledger
  FOR EACH ROW EXECUTE FUNCTION inventory.enforce_ledger_append_only();

-- ── 2. the sign convention ──────────────────────────────────────────────────
-- Positive in, negative out, and `sum(qty_base)` is therefore the balance. A
-- movement type that disagrees with its own sign would make every balance in
-- the system arithmetically valid and physically wrong.
ALTER TABLE inventory.stock_ledger
  ADD CONSTRAINT stock_ledger_sign_matches_movement
  CHECK (
    qty_base <> 0
    AND (
      CASE
        WHEN movement_type IN (
          'opening', 'grn', 'purchase_free', 'transfer_in', 'issue_in', 'return_in',
          'patient_return', 'consignment_in', 'repack_in', 'adjustment_plus', 'count_gain'
        ) THEN qty_base > 0
        WHEN movement_type IN (
          'issue_out', 'transfer_out', 'dispense', 'consumption', 'sale', 'vendor_return',
          'expiry_writeoff', 'damage_writeoff', 'wastage', 'consignment_used',
          'consignment_return', 'repack_out', 'adjustment_minus', 'count_loss'
        ) THEN qty_base < 0
        -- `correction` is the only type that may carry either sign, because it
        -- must be able to undo either kind of mistake.
        ELSE true
      END
    )
  );

-- A correction names what it corrects and says why. Both together or neither —
-- a compensating entry with no explanation is indistinguishable from a fresh
-- error, and that is the thing an auditor is trying to tell apart.
ALTER TABLE inventory.stock_ledger
  ADD CONSTRAINT stock_ledger_correction_documented
  CHECK (
    (movement_type = 'correction') = (corrects_ledger_id IS NOT NULL)
    AND (corrects_ledger_id IS NULL OR (reason IS NOT NULL AND length(btrim(reason)) > 0))
  );

-- ── 3. the preconditions ────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION inventory.enforce_ledger_preconditions()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_tracking     "inventory"."InvTracking";
  v_is_narcotic  boolean;
  v_schedule     "mdm"."MdmDrugSchedule";
  v_item_code    text;
  v_expiry       date;
  v_batch_status "inventory"."InvBatchStatus";
  v_batch_no     text;
  v_holds_narc   boolean;
  v_store_code   text;
  v_corrected    record;
BEGIN
  SELECT i.tracking, i.is_narcotic, i.schedule, i.code
    INTO v_tracking, v_is_narcotic, v_schedule, v_item_code
  FROM inventory.items i WHERE i.id = NEW.item_id;

  IF v_item_code IS NULL THEN
    RAISE EXCEPTION 'inventory.stock_ledger: item % does not exist', NEW.item_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  -- A batch-tracked item without a batch is a row that no recall can ever
  -- reach and no expiry check can ever evaluate.
  IF v_tracking IN ('batch', 'batch_expiry', 'udi') AND NEW.batch_id IS NULL THEN
    RAISE EXCEPTION
      'inventory.stock_ledger: item % is batch-tracked, so every movement of it must name a batch. A movement with no batch is invisible to a recall.',
      v_item_code
      USING ERRCODE = 'check_violation';
  END IF;

  -- Narcotics live in a designated store and nowhere else.
  SELECT s.holds_narcotics, s.code INTO v_holds_narc, v_store_code
  FROM inventory.stores s WHERE s.id = NEW.store_id;

  IF v_store_code IS NULL THEN
    RAISE EXCEPTION 'inventory.stock_ledger: store % does not exist', NEW.store_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  IF (v_is_narcotic OR v_schedule IN ('ndps_narcotic', 'ndps_psychotropic'))
     AND NOT coalesce(v_holds_narc, false)
  THEN
    RAISE EXCEPTION
      'inventory.stock_ledger: % is a controlled drug and store % is not designated to hold narcotics (phase-04 §4.2: "narcotics stored and reconciled separately").',
      v_item_code, v_store_code
      USING ERRCODE = 'check_violation';
  END IF;

  -- ── the expiry and quarantine refusals — phase-04 exit gate 3 ────────────
  IF NEW.batch_id IS NOT NULL THEN
    SELECT b.expiry_date, b.status, b.batch_no
      INTO v_expiry, v_batch_status, v_batch_no
    FROM inventory.item_batches b WHERE b.id = NEW.batch_id;

    IF v_batch_no IS NULL THEN
      RAISE EXCEPTION 'inventory.stock_ledger: batch % does not exist', NEW.batch_id
        USING ERRCODE = 'foreign_key_violation';
    END IF;

    -- Movements that put stock into a patient, a department or a customer.
    -- Everything else — a write-off, a quarantine transfer, a return to the
    -- supplier — is precisely how expired stock is supposed to leave, so those
    -- must stay possible.
    IF NEW.movement_type IN ('dispense', 'sale', 'issue_out', 'consumption', 'consignment_used') THEN
      IF v_expiry IS NOT NULL AND v_expiry <= NEW.moved_at::date THEN
        RAISE EXCEPTION
          'inventory.stock_ledger: batch % of % expired on % and cannot be dispensed or issued. Write it off (expiry_writeoff) or return it (vendor_return).',
          v_batch_no, v_item_code, v_expiry
          USING ERRCODE = 'check_violation';
      END IF;

      IF v_batch_status IN ('quarantined', 'recalled', 'expired', 'written_off', 'returned_to_vendor') THEN
        RAISE EXCEPTION
          'inventory.stock_ledger: batch % of % is %, and stock in that state does not leave the shelf towards a patient.',
          v_batch_no, v_item_code, v_batch_status
          USING ERRCODE = 'check_violation';
      END IF;

      -- An open quarantine on the batch blocks it even if the batch row has not
      -- been re-stamped yet. `pending` is the state that matters: an undecided
      -- excursion is not a released one.
      IF EXISTS (
        SELECT 1 FROM inventory.quarantines q
        WHERE q.batch_id = NEW.batch_id
          AND q.decision = 'pending'
          AND (q.scope = 'all_stores' OR q.store_id = NEW.store_id)
      ) THEN
        RAISE EXCEPTION
          'inventory.stock_ledger: batch % of % is under an undecided quarantine. Release it, or return or destroy it — an undecided quarantine is not a released one.',
          v_batch_no, v_item_code
          USING ERRCODE = 'check_violation';
      END IF;
    END IF;
  END IF;

  -- ── corrections ─────────────────────────────────────────────────────────
  IF NEW.corrects_ledger_id IS NOT NULL THEN
    SELECT l.id, l.movement_type, l.store_id, l.item_id
      INTO v_corrected
    FROM inventory.stock_ledger l
    WHERE l.id = NEW.corrects_ledger_id
    LIMIT 1;

    IF v_corrected.id IS NULL THEN
      RAISE EXCEPTION
        'inventory.stock_ledger: correction names movement %, which does not exist.',
        NEW.corrects_ledger_id
        USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF v_corrected.movement_type = 'correction' THEN
      RAISE EXCEPTION
        'inventory.stock_ledger: movement % is itself a correction. Correct the original movement, not the correction of it — a chain of corrections is unreadable to the person who has to reconstruct what happened.',
        NEW.corrects_ledger_id
        USING ERRCODE = 'check_violation';
    END IF;

    IF v_corrected.store_id <> NEW.store_id OR v_corrected.item_id <> NEW.item_id THEN
      RAISE EXCEPTION
        'inventory.stock_ledger: a correction must be for the same item in the same store as the movement it corrects.'
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION inventory.enforce_ledger_preconditions IS
  'Everything a movement must satisfy before it is recorded: a batch-tracked item names a batch, a controlled drug is in a designated store, and — phase-04 exit gate 3 — an expired, quarantined or recalled batch cannot move towards a patient. Enforced here rather than in a service so it holds on every path, including a bulk import and a repository somebody writes next year.';

DROP TRIGGER IF EXISTS trg_stock_ledger_preconditions ON inventory.stock_ledger;
CREATE TRIGGER trg_stock_ledger_preconditions
  BEFORE INSERT ON inventory.stock_ledger
  FOR EACH ROW EXECUTE FUNCTION inventory.enforce_ledger_preconditions();

-- ── 4. the balance projection ───────────────────────────────────────────────
-- The upsert key. `NULLS NOT DISTINCT` because `location_id` and `batch_id` are
-- legitimately null (a non-binned store, a serial-only item) and without it two
-- rows for the same position would both be insertable and the balance would
-- split in two.
CREATE UNIQUE INDEX IF NOT EXISTS uq_stock_balances_position
  ON inventory.stock_balances (store_id, location_id, item_id, batch_id) NULLS NOT DISTINCT;

CREATE OR REPLACE FUNCTION inventory.apply_ledger_to_balance()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_policy   "inventory"."InvNegativeStockPolicy";
  v_store    text;
  v_item     text;
  v_on_hand  numeric;
  v_new_avg  numeric;
BEGIN
  -- Weighted average moves only on the way in, and only on a movement that has
  -- a cost. An issue at the current average does not change the average; a GRN
  -- at a different price does.
  INSERT INTO inventory.stock_balances AS b (
    id, hospital_id, branch_id, store_id, location_id, item_id, batch_id,
    qty_on_hand, qty_reserved, qty_quarantined, qty_in_transit_in,
    avg_cost, value, is_consignment, last_movement_at, created_at, updated_at
  )
  VALUES (
    gen_random_uuid(), NEW.hospital_id, NEW.branch_id, NEW.store_id, NEW.location_id,
    NEW.item_id, NEW.batch_id,
    NEW.qty_base, 0, 0, 0,
    coalesce(NEW.unit_cost, 0),
    round(NEW.qty_base * coalesce(NEW.unit_cost, 0), 2),
    NEW.is_consignment, NEW.moved_at, now(), now()
  )
  ON CONFLICT (store_id, location_id, item_id, batch_id) DO UPDATE
  SET qty_on_hand = b.qty_on_hand + NEW.qty_base,
      avg_cost = CASE
        WHEN NEW.qty_base > 0 AND NEW.unit_cost IS NOT NULL AND (b.qty_on_hand + NEW.qty_base) <> 0
          THEN round(
                 ((b.qty_on_hand * b.avg_cost) + (NEW.qty_base * NEW.unit_cost))
                 / (b.qty_on_hand + NEW.qty_base), 4)
        ELSE b.avg_cost
      END,
      last_movement_at = greatest(b.last_movement_at, NEW.moved_at),
      is_consignment = b.is_consignment OR NEW.is_consignment,
      updated_at = now()
  RETURNING b.qty_on_hand, b.avg_cost INTO v_on_hand, v_new_avg;

  UPDATE inventory.stock_balances
  SET value = round(qty_on_hand * avg_cost, 2)
  WHERE store_id = NEW.store_id
    AND location_id IS NOT DISTINCT FROM NEW.location_id
    AND item_id = NEW.item_id
    AND batch_id IS NOT DISTINCT FROM NEW.batch_id;

  -- Negative stock. `block` is the default and the only safe setting for a
  -- dispensing counter — `phase-04 §Constraints`: "fail closed on stock
  -- integrity". A store may be configured to allow it, and then the exception
  -- report is what surfaces it.
  IF v_on_hand < 0 THEN
    SELECT s.negative_stock_policy, s.code INTO v_policy, v_store
    FROM inventory.stores s WHERE s.id = NEW.store_id;

    IF v_policy = 'block' THEN
      SELECT i.code INTO v_item FROM inventory.items i WHERE i.id = NEW.item_id;
      RAISE EXCEPTION
        'inventory.stock_ledger: this movement would take % in store % to % base units. Store % blocks negative stock. Count the shelf and post an adjustment before issuing what is not there.',
        v_item, v_store, v_on_hand, v_store
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  RETURN NULL;
END;
$$;

COMMENT ON FUNCTION inventory.apply_ledger_to_balance IS
  'The only writer of inventory.stock_balances. Because it is the only one, sum(stock_ledger.qty_base) = stock_balances.qty_on_hand holds by construction rather than by a nightly job that has stopped running. The ON CONFLICT takes a row lock, which is also what serialises two counters racing for the last unit.';

DROP TRIGGER IF EXISTS trg_stock_ledger_project_balance ON inventory.stock_ledger;
CREATE TRIGGER trg_stock_ledger_project_balance
  AFTER INSERT ON inventory.stock_ledger
  FOR EACH ROW EXECUTE FUNCTION inventory.apply_ledger_to_balance();

-- ── 5. the integrity verifier — phase-04 exit gate 6 ────────────────────────
CREATE OR REPLACE FUNCTION inventory.verify_stock_integrity(p_hospital_id uuid DEFAULT NULL)
RETURNS TABLE (
  store_id      uuid,
  item_id       uuid,
  batch_id      uuid,
  ledger_sum    numeric,
  balance_qty   numeric,
  difference    numeric
)
LANGUAGE sql
STABLE
AS $$
  WITH ledger AS (
    SELECT l.store_id, l.item_id, l.batch_id, sum(l.qty_base) AS ledger_sum
    FROM inventory.stock_ledger l
    WHERE p_hospital_id IS NULL OR l.hospital_id = p_hospital_id
    GROUP BY l.store_id, l.item_id, l.batch_id
  ),
  balance AS (
    SELECT b.store_id, b.item_id, b.batch_id, sum(b.qty_on_hand) AS balance_qty
    FROM inventory.stock_balances b
    WHERE p_hospital_id IS NULL OR b.hospital_id = p_hospital_id
    GROUP BY b.store_id, b.item_id, b.batch_id
  )
  SELECT
    coalesce(l.store_id, b.store_id),
    coalesce(l.item_id, b.item_id),
    coalesce(l.batch_id, b.batch_id),
    coalesce(l.ledger_sum, 0),
    coalesce(b.balance_qty, 0),
    coalesce(l.ledger_sum, 0) - coalesce(b.balance_qty, 0)
  FROM ledger l
  FULL OUTER JOIN balance b
    ON  b.store_id = l.store_id
    AND b.item_id  = l.item_id
    AND b.batch_id IS NOT DISTINCT FROM l.batch_id
  WHERE coalesce(l.ledger_sum, 0) <> coalesce(b.balance_qty, 0);
$$;

COMMENT ON FUNCTION inventory.verify_stock_integrity IS
  'phase-04 exit gate 6: "run the stock-integrity test (sum(ledger) == on_hand for every item/batch/store) and it passes". Returns the rows where it does not. An empty result is the pass condition; anything else is a defect in the projection trigger, not in the data.';

GRANT EXECUTE ON FUNCTION inventory.verify_stock_integrity(uuid) TO hms_app, hms_readonly;

-- ── the FEFO helper ─────────────────────────────────────────────────────────
-- First-expiry-first-out, as a function rather than as a convention in each
-- caller. A picker may override the suggestion (`pick_list_lines.picked_batch_id`
-- differing from `suggested_batch_id`), and then the reason is mandatory.
CREATE OR REPLACE FUNCTION inventory.fefo_batches(
  p_hospital_id uuid,
  p_store_id    uuid,
  p_item_id     uuid,
  p_as_of       date DEFAULT current_date
)
RETURNS TABLE (batch_id uuid, expiry_date date, qty_available numeric, unit_cost numeric)
LANGUAGE sql
STABLE
AS $$
  SELECT b.batch_id, ib.expiry_date,
         sum(b.qty_on_hand - b.qty_reserved) AS qty_available,
         max(b.avg_cost) AS unit_cost
  FROM inventory.stock_balances b
  JOIN inventory.item_batches ib ON ib.id = b.batch_id
  WHERE b.hospital_id = p_hospital_id
    AND b.store_id = p_store_id
    AND b.item_id = p_item_id
    AND ib.status = 'active'
    AND (ib.expiry_date IS NULL OR ib.expiry_date > p_as_of)
    AND NOT EXISTS (
      SELECT 1 FROM inventory.quarantines q
      WHERE q.batch_id = b.batch_id AND q.decision = 'pending'
        AND (q.scope = 'all_stores' OR q.store_id = p_store_id)
    )
  GROUP BY b.batch_id, ib.expiry_date
  HAVING sum(b.qty_on_hand - b.qty_reserved) > 0
  -- NULLS LAST so a batch with no expiry is picked only after every dated one.
  ORDER BY ib.expiry_date ASC NULLS LAST, b.batch_id;
$$;

COMMENT ON FUNCTION inventory.fefo_batches IS
  'The issuable batches of one item in one store, soonest expiry first. Excludes expired, non-active and quarantined batches — the same three exclusions inventory.enforce_ledger_preconditions() enforces, so a suggestion this returns can never be one the ledger would then refuse.';

GRANT EXECUTE ON FUNCTION inventory.fefo_batches(uuid, uuid, uuid, date) TO hms_app, hms_readonly;

