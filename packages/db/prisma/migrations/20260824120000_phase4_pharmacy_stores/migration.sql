-- ── C.1 the UoM ladder: the database converts, it does not trust ────────────
--
-- `phase-04 §Constraints`: "Every quantity has a UoM. Any arithmetic mixing
-- UoMs without conversion is a bug — write property-based tests."
--
-- The property tests are in `packages/contracts/src/primitives/uom.spec.ts` and
-- they prove the arithmetic. They cannot prove that every *caller* remembered to
-- do it, and that is the failure that actually happens: a repository writes
-- `qty_base = qty` because for the item it was tested against a strip happened
-- to be one tablet. The result is a balance that is wrong by a factor of ten,
-- discovered at a stock count months later.
--
-- So the conversion is checked where it cannot be skipped. Three functions:
--
--   `inventory.enforce_item_uom()`   the ladder itself is well-formed: the base
--                                    rung has factor 1, no rung has a factor of
--                                    zero or less, and no rung crosses
--                                    dimensions — because no factor turns
--                                    millilitres into tablets, and a row that
--                                    claims to is a typo with consequences.
--   `inventory.enforce_qty_uom()`    a generic row trigger, attached to every
--                                    table carrying an (item, uom, qty_entered,
--                                    qty_base) quadruple. It looks the factor
--                                    up and refuses the row when the arithmetic
--                                    disagrees. The columns are passed as
--                                    trigger arguments so one function serves
--                                    all sixteen tables.
--   `inventory.refuse_base_uom_change()`  changing an item's base UoM after a
--                                    ledger row exists would silently restate
--                                    every historic quantity.
-- ═════════════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION inventory.enforce_item_uom()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_item_dimension "mdm"."MdmUomDimension";
  v_uom_dimension  "mdm"."MdmUomDimension";
  v_base_uom_id    uuid;
BEGIN
  IF NEW.factor_to_base IS NULL OR NEW.factor_to_base <= 0 THEN
    RAISE EXCEPTION
      'inventory.item_uoms: factor_to_base must be > 0 (item %, uom %). A factor of zero or less is not a pack size.',
      NEW.item_id, NEW.uom_id
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT i.base_uom_id INTO v_base_uom_id FROM inventory.items i WHERE i.id = NEW.item_id;
  IF v_base_uom_id IS NULL THEN
    RAISE EXCEPTION 'inventory.item_uoms: item % does not exist', NEW.item_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  -- The base rung is the one naming the item's base UoM, and its factor is 1 by
  -- definition. Both directions are checked: a rung that names the base UoM but
  -- is not marked `is_base` would make `sum()` over the ladder ambiguous.
  IF (NEW.uom_id = v_base_uom_id) <> NEW.is_base THEN
    RAISE EXCEPTION
      'inventory.item_uoms: is_base must be true for exactly the item''s base UoM (item %, uom %, base %)',
      NEW.item_id, NEW.uom_id, v_base_uom_id
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.is_base AND NEW.factor_to_base <> 1 THEN
    RAISE EXCEPTION
      'inventory.item_uoms: the base rung of item % must have factor_to_base = 1, not %',
      NEW.item_id, NEW.factor_to_base
      USING ERRCODE = 'check_violation';
  END IF;

  -- Dimensions must agree. A strip is 10 tablets (count → count); nothing
  -- converts millilitres to tablets, and a row that claims to would let the
  -- balance of a syrup be computed in tablets.
  SELECT dimension INTO v_item_dimension FROM mdm.mdm_uoms WHERE id = v_base_uom_id;
  SELECT dimension INTO v_uom_dimension  FROM mdm.mdm_uoms WHERE id = NEW.uom_id;

  IF v_uom_dimension IS NULL THEN
    RAISE EXCEPTION 'inventory.item_uoms: uom % does not exist', NEW.uom_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  IF v_item_dimension IS DISTINCT FROM v_uom_dimension THEN
    RAISE EXCEPTION
      'inventory.item_uoms: cannot convert % to % for item % — a conversion factor between different dimensions is a data-entry error, not a conversion',
      v_uom_dimension, v_item_dimension, NEW.item_id
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION inventory.enforce_item_uom IS
  'The conversion ladder is well-formed: the base rung has factor 1, every rung has a positive factor, and no rung crosses UoM dimensions. Without the last check, "1 strip = 10 ml" against an item stocked in tablets is storable, and every balance for that item is then wrong in a way no report shows.';

DROP TRIGGER IF EXISTS trg_item_uoms_enforce ON inventory.item_uoms;
CREATE TRIGGER trg_item_uoms_enforce
  BEFORE INSERT OR UPDATE ON inventory.item_uoms
  FOR EACH ROW EXECUTE FUNCTION inventory.enforce_item_uom();

-- Exactly one base rung per item.
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_uoms_one_base
  ON inventory.item_uoms (item_id) WHERE is_base;

-- At most one default per purpose per item — otherwise "the purchase UoM" has
-- two answers and the one a screen gets depends on the plan.
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_uoms_one_purchase_default
  ON inventory.item_uoms (item_id) WHERE is_purchase_default;
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_uoms_one_issue_default
  ON inventory.item_uoms (item_id) WHERE is_issue_default;
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_uoms_one_dispense_default
