-- ═════════════════════════════════════════════════════════════════════════════
-- §A. MONTHLY PARTITIONS
--
-- `core.ensure_month_partition()` (defined in ..._partitions_and_indexes,
-- extended in ..._rls_policies) creates one month, enables RLS on it, attaches
-- the tenant policies, grants and storage parameters — so a partition the worker
-- creates in 2032 is protected exactly like one created here.
--
-- ── Why this phase uses the base helper and not Phase 3's writable one ──────
--
-- Phase 3 had to add `core.ensure_month_partition_writable()` because five of
-- its six partitioned tables stamp state forward on the same row. None of the
-- three here does, and that is the phase's central guarantee rather than an
-- accident of the data:
--
--   `inventory.stock_ledger`   a mistaken row is corrected by a compensating
--                              row naming it (`corrects_ledger_id` + a reason).
--                              `phase-04 §Constraints` is explicit that an
--                              UPDATE is a defect, so a partition that could
--                              accept one would be a loaded gun in April.
--   `inventory.temp_readings`  a measurement. The excursion flag is set by a
--                              BEFORE INSERT trigger against the zone's bounds,
--                              so it is decided once, at write time.
--   `inventory.vnd_events`     a fact about a receipt that already happened.
--                              The *score* derived from it is recomputed; the
--                              fact is not.
--
-- ── Why every partition key here is `timestamptz(3)` ────────────────────────
--
-- Identical reasoning to Phases 2 and 3, and it has not become less true. A
-- partitioned table's primary key must contain its partitioning column, so all
-- three carry a composite key `(id, <timestamp>)`. At `timestamptz(6)`
-- PostgreSQL stores microseconds and a JavaScript `Date` holds milliseconds, so
-- a key read into an application object and written back matches **zero rows**
-- — silently, because an UPDATE that affects nothing is not an error. Nothing
-- here is measured to the microsecond: a stock movement, a fridge reading and a
-- vendor performance fact are all events whose ordering within a millisecond
-- comes from the time-ordered UUIDv7 in `id`.
--
-- Premake the current month, three ahead and one behind: a back-dated GRN from
-- the downtime protocol (docs/01 §7), or an opening-stock load dated to the
-- previous month end, must have somewhere to land.
-- ═════════════════════════════════════════════════════════════════════════════

DO $$
DECLARE
  v_tables text[][] := ARRAY[
    ['inventory', 'stock_ledger'],
    ['inventory', 'temp_readings'],
    ['inventory', 'vnd_events']
  ];
  i int;
  m int;
BEGIN
  FOR i IN 1 .. array_length(v_tables, 1) LOOP
    FOR m IN -1 .. 3 LOOP
      PERFORM core.ensure_month_partition(
        v_tables[i][1],
        v_tables[i][2],
        (date_trunc('month', now()) + (m || ' month')::interval)::date
      );
    END LOOP;
  END LOOP;
END
$$;

-- ── DEFAULT partitions ───────────────────────────────────────────────────────
-- Without one, an INSERT whose timestamp falls outside every declared range
-- fails. For `inventory.stock_ledger` that failure would refuse to record a
-- movement that has physically happened — the worst possible way for a stock
-- system to fail, because the medicine left the shelf whether or not the
-- database will say so, and the next dispense would then be computed from a
-- balance that is wrong. A default partition turns it into a monitored anomaly:
-- a non-empty default partition is alertable, never normal.
DO $$
DECLARE
  v_tables text[][] := ARRAY[
    ['inventory', 'stock_ledger'],
    ['inventory', 'temp_readings'],
    ['inventory', 'vnd_events']
  ];
  i int;
  v_schema     text;
  v_table      text;
  v_default    text;
  v_qualified  text;
  v_using      text;
  v_has_branch boolean;
BEGIN
  FOR i IN 1 .. array_length(v_tables, 1) LOOP
    v_schema  := v_tables[i][1];
    v_table   := v_tables[i][2];
    v_default := v_table || '_default';
    v_qualified := format('%I.%I', v_schema, v_default);

    IF NOT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = v_schema AND c.relname = v_default
    ) THEN
      EXECUTE format('CREATE TABLE %s PARTITION OF %I.%I DEFAULT', v_qualified, v_schema, v_table);
    END IF;

    SELECT count(*) FILTER (WHERE column_name = 'branch_id') > 0
    INTO v_has_branch
    FROM information_schema.columns
    WHERE table_schema = v_schema AND table_name = v_table;

    v_using := 'hospital_id = ANY (core.accessible_hospital_ids())';
    IF v_has_branch THEN
      v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
    END IF;

    EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', v_qualified);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %s', v_qualified);
    EXECUTE format('CREATE POLICY tenant_isolation ON %s FOR ALL TO hms_app USING (%s) WITH CHECK (%s)',
                   v_qualified, v_using, v_using);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_ro ON %s', v_qualified);
    EXECUTE format('CREATE POLICY tenant_isolation_ro ON %s FOR SELECT TO hms_readonly USING (%s)',
                   v_qualified, v_using);

    -- SELECT and INSERT only. Same rule as the dated partitions: nothing in
    -- this phase updates a partitioned row, and the default partition must not
    -- be the one place where it could.
    EXECUTE format('GRANT SELECT, INSERT ON %s TO hms_app', v_qualified);
    EXECUTE format('GRANT SELECT ON %s TO hms_readonly', v_qualified);

    EXECUTE format(
      'COMMENT ON TABLE %s IS %L',
      v_qualified,
      'Safety net only. A non-empty default partition is an alertable anomaly (docs/07 §6), never a normal state.'
    );
  END LOOP;
END
$$;


