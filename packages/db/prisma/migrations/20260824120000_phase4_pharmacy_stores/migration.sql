-- ── C.2 effective-dated prices: never retroactive, never overlapping ────────
--
-- `phase-04 §Constraints`: "GST/HSN on every item; price changes are
-- effective-dated, never retroactive."
--
-- Two failures are being prevented and they are different. **Overlap** means
-- "the price on 12 August" has two answers and which one a bill gets depends on
-- the plan — caught by a btree_gist EXCLUDE, which is a constraint rather than a
-- check because it is a statement about pairs of rows. **Retroaction** means a
-- price is changed for a period that has already been billed, which restates
-- invoices that are already in a customer's hands — caught by a trigger,
-- because the rule is about *now* and a constraint cannot see the clock.
--
-- A price is superseded by writing the next one, never by editing this one.
-- ═════════════════════════════════════════════════════════════════════════════

CREATE EXTENSION IF NOT EXISTS btree_gist SCHEMA ext;

-- One GST rate per HSN per day.
ALTER TABLE mdm.mdm_gst_rates
  ADD CONSTRAINT mdm_gst_rates_no_overlap
  EXCLUDE USING gist (
    hsn_code_id WITH =,
    daterange(effective_from, effective_to, '[)') WITH &&
  );

-- CGST + SGST must equal IGST, or the same sale is taxed two different ways
-- depending on where the customer is.
ALTER TABLE mdm.mdm_gst_rates
  ADD CONSTRAINT mdm_gst_rates_split_consistent
  CHECK (round(cgst_rate + sgst_rate, 2) = round(igst_rate, 2));

ALTER TABLE mdm.mdm_gst_rates
  ADD CONSTRAINT mdm_gst_rates_period_ordered
  CHECK (effective_to IS NULL OR effective_to > effective_from);

-- One DPCO ceiling per formulation per day.
ALTER TABLE mdm.mdm_dpco_ceilings
  ADD CONSTRAINT mdm_dpco_ceilings_no_overlap
  EXCLUDE USING gist (
    formulation WITH =,
    daterange(effective_from, effective_to, '[)') WITH &&
  );

ALTER TABLE mdm.mdm_dpco_ceilings
  ADD CONSTRAINT mdm_dpco_ceilings_positive
  CHECK (ceiling_price > 0);

-- One item price per (item, branch, kind) per day. `branch_id` is nullable and
-- NULLs are distinct in an EXCLUDE, so it is coalesced to the nil UUID —
-- otherwise two hospital-wide prices for the same day would both be storable.
ALTER TABLE inventory.item_prices
  ADD CONSTRAINT item_prices_no_overlap
  EXCLUDE USING gist (
    item_id WITH =,
    (coalesce(branch_id, '00000000-0000-0000-0000-000000000000'::uuid)) WITH =,
    price_kind WITH =,
    daterange(effective_from, effective_to, '[)') WITH &&
  );

ALTER TABLE inventory.item_prices
  ADD CONSTRAINT item_prices_non_negative
  CHECK (unit_price >= 0 AND max_discount_pct BETWEEN 0 AND 100);

-- One contracted rate per (contract, item) per day.
ALTER TABLE inventory.vnd_rate_contract_lines
  ADD CONSTRAINT vnd_rate_contract_lines_no_overlap
  EXCLUDE USING gist (
    contract_id WITH =,
    item_id WITH =,
    daterange(valid_from, valid_to, '[)') WITH &&
  );

-- One consignment price per (agreement, item) per day.
ALTER TABLE inventory.csn_agreement_items
  ADD CONSTRAINT csn_agreement_items_no_overlap
  EXCLUDE USING gist (
    agreement_id WITH =,
    item_id WITH =,
    daterange(price_valid_from, price_valid_to, '[)') WITH &&
  );

CREATE OR REPLACE FUNCTION inventory.refuse_retroactive_price()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.effective_from < current_date THEN
      RAISE EXCEPTION
        'inventory.item_prices: effective_from % is in the past. A price change is effective-dated, never retroactive (phase-04 §Constraints) — a bill already printed must stay reproducible. Date it today or later.',
        NEW.effective_from
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  -- An UPDATE may only close a period that has not yet started, or set the
  -- `effective_to` of a live one. The money itself is frozen the moment the
  -- period begins.
  IF OLD.effective_from <= current_date THEN
    IF NEW.unit_price IS DISTINCT FROM OLD.unit_price
       OR NEW.effective_from IS DISTINCT FROM OLD.effective_from
       OR NEW.item_id IS DISTINCT FROM OLD.item_id
       OR NEW.price_kind IS DISTINCT FROM OLD.price_kind
       OR NEW.currency IS DISTINCT FROM OLD.currency
    THEN
      RAISE EXCEPTION
        'inventory.item_prices: the price of item % from % is in force and cannot be edited. Supersede it with a new row effective from a future date.',
        OLD.item_id, OLD.effective_from
        USING ERRCODE = 'restrict_violation';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION inventory.refuse_retroactive_price IS
  'A price is dated forward and superseded, never edited. The EXCLUDE constraint stops two prices covering one day; this stops one price being rewritten under a bill that already used it.';

DROP TRIGGER IF EXISTS trg_item_prices_no_retroaction ON inventory.item_prices;
CREATE TRIGGER trg_item_prices_no_retroaction
  BEFORE INSERT OR UPDATE ON inventory.item_prices
  FOR EACH ROW EXECUTE FUNCTION inventory.refuse_retroactive_price();

-- ── the DPCO ceiling, applied ───────────────────────────────────────────────
-- `mdm_drugs.dpco_scheduled` is already enforced against a brand's MRP by the
-- Phase-2 migration. This is the same rule one level down, where it actually
-- bites: the MRP printed on the *batch* that was received.
CREATE OR REPLACE FUNCTION inventory.enforce_dpco_ceiling()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_scheduled boolean;
  v_drug_key  uuid;
  v_ceiling   numeric;
BEGIN
  IF NEW.mrp IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT i.dpco_scheduled, i.drug_key INTO v_scheduled, v_drug_key
  FROM inventory.items i WHERE i.id = NEW.item_id;

  IF NOT coalesce(v_scheduled, false) OR v_drug_key IS NULL THEN
    RETURN NEW;
  END IF;

  -- The ceiling in force on the day the batch was received, not today. A
  -- notification that lands next month does not make last month's batch illegal.
  SELECT c.ceiling_price INTO v_ceiling
  FROM mdm.mdm_dpco_ceilings c
  WHERE c.drug_key = v_drug_key
    AND c.effective_from <= NEW.received_at::date
    AND (c.effective_to IS NULL OR c.effective_to > NEW.received_at::date)
  ORDER BY c.effective_from DESC
  LIMIT 1;

  IF v_ceiling IS NOT NULL AND NEW.mrp > v_ceiling THEN
    RAISE EXCEPTION
      'inventory.item_batches: MRP % on batch % exceeds the DPCO notified ceiling of % in force on %. Selling above a notified ceiling is an offence under the Drugs (Prices Control) Order 2013.',
      NEW.mrp, NEW.batch_no, v_ceiling, NEW.received_at::date
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_item_batches_dpco ON inventory.item_batches;
CREATE TRIGGER trg_item_batches_dpco
  BEFORE INSERT OR UPDATE ON inventory.item_batches
  FOR EACH ROW EXECUTE FUNCTION inventory.enforce_dpco_ceiling();

-- ── the batch's own integrity ───────────────────────────────────────────────
-- An item whose tracking demands an expiry must have one. This is the root of
-- `phase-04` exit gate 3 — an expired batch cannot be blocked at dispensing if
-- it never carried an expiry to compare against.
