COMMENT ON TABLE pharmacy.dispense_items IS
  'OP-003 §4. One drug, one batch, one quantity, and the row a recall trace lands on. A batch-tracked line must name a batch (phase-04 §Constraints: never dispense without a successful batch validation); a partial fill must say why; a substitution must name what it replaced; a FEFO override must justify itself. The Schedule H over-the-counter refusal and the NDPS second-authoriser requirement are enforced here, not in a service, so they hold on every path.';
COMMENT ON TABLE pharmacy.recalls IS
