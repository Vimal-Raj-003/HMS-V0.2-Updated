-- ── 5. the retention role ──────────────────────────────────────────────────
--    Note what is NOT here. `inventory.stock_ledger` is partitioned, but it is
--    the financial record of every movement of medicine in the hospital and
--    `docs/04` retention for financial records is eight years; no sweeper may
--    remove it. Its partitions are detached by `hms_migrator` under an explicit
--    release procedure (docs/13), never by a job.
--
--    `inventory.temp_readings` is genuinely operational: a fridge reporting
--    every five minutes is telemetry, the *excursions* derived from it are the
--    evidence and they live in their own table with no retention grant.
--    `inventory.vnd_events` is the same shape — the score computed from it is
--    kept, the raw facts age out.
GRANT SELECT, DELETE ON inventory.temp_readings TO hms_retention;
GRANT SELECT, DELETE ON inventory.vnd_events    TO hms_retention;

DO $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      ('inventory', 'temp_readings'),
      ('inventory', 'vnd_events')
    ) AS t(schema_name, table_name)
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS retention_all_tenants ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY retention_all_tenants ON %I.%I FOR ALL TO hms_retention USING (true) WITH CHECK (true)',
      r.schema_name, r.table_name
    );
  END LOOP;
END
$$;

-- ── 6. assert the grants match the intent ──────────────────────────────────
-- A migration that half-applied its own security is worse than one that failed,
-- because it looks finished.
DO $$
DECLARE
  v_bad text;
BEGIN
  SELECT string_agg(format('%s.%s', table_schema, table_name), ', ' ORDER BY table_schema, table_name)
  INTO v_bad
  FROM core.v_grant_coverage
  WHERE readonly_has_write;

  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'Phase 4 granted write privileges to hms_readonly on: %', v_bad;
  END IF;

  -- **The assertion this whole phase turns on.**
  IF has_table_privilege('hms_app', 'inventory.stock_ledger', 'UPDATE')
     OR has_table_privilege('hms_app', 'inventory.stock_ledger', 'DELETE')
  THEN
    RAISE EXCEPTION
      'inventory.stock_ledger is mutable by hms_app. phase-04 §Constraints: "The stock ledger never gets an UPDATE. Corrections are new compensating entries with reason." A ledger that can be edited is not a ledger.';
  END IF;

  -- And the same for every partition, present and future. A partition that
  -- arrived writable would make the parent's revoke cosmetic.
  SELECT string_agg(format('%s.%s', n.nspname, c.relname), ', ')
  INTO v_bad
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE c.relispartition
    AND c.relname LIKE 'stock_ledger%'
    AND n.nspname = 'inventory'
    AND (has_table_privilege('hms_app', c.oid, 'UPDATE') OR has_table_privilege('hms_app', c.oid, 'DELETE'));

  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'These stock_ledger partitions are mutable by hms_app: %', v_bad;
  END IF;

  IF has_table_privilege('hms_app', 'pharmacy.controlled_drug_register', 'UPDATE')
     OR has_table_privilege('hms_app', 'pharmacy.controlled_drug_register', 'DELETE')
  THEN
    RAISE EXCEPTION
      'pharmacy.controlled_drug_register is mutable by hms_app. It is a statutory register under the NDPS Act and the Drugs & Cosmetics Rules; a register that can be edited after the fact documents nothing.';
  END IF;

  IF has_table_privilege('hms_app', 'pharmacy.narcotic_custody_checks', 'UPDATE')
     OR has_table_privilege('hms_app', 'pharmacy.narcotic_custody_checks', 'DELETE')
  THEN
    RAISE EXCEPTION
      'pharmacy.narcotic_custody_checks is mutable by hms_app. phase-04 exit gate 4: a deliberate mismatch "cannot be silently adjusted" — which is untrue if the count itself can be rewritten.';
  END IF;

  -- Batches, dispenses and every purchase document are financial or clinical
  -- records and are never hard-deleted.
  IF has_table_privilege('hms_app', 'inventory.item_batches', 'DELETE')
     OR has_table_privilege('hms_app', 'pharmacy.dispense_items', 'DELETE')
     OR has_table_privilege('hms_app', 'inventory.pur_grn_lines', 'DELETE')
     OR has_table_privilege('hms_app', 'inventory.csn_usages', 'DELETE')
  THEN
    RAISE EXCEPTION
      'A batch, dispensed line, goods-receipt line or consignment usage is deletable by hms_app. CLAUDE.md §4: clinical and financial rows are never hard-deleted.';
  END IF;
END
$$;

-- Assert the triggers this phase depends on are actually attached. A trigger
-- that failed to create leaves a migration that looks finished and a database
-- that is not.
DO $$
DECLARE
  v_missing text;
BEGIN
  SELECT string_agg(t.name, ', ' ORDER BY t.name)
  INTO v_missing
  FROM (VALUES
    ('trg_stock_ledger_append_only',        'inventory.stock_ledger'),
    ('trg_stock_ledger_preconditions',      'inventory.stock_ledger'),
    ('trg_stock_ledger_project_balance',    'inventory.stock_ledger'),
    ('trg_controlled_register_append_only', 'pharmacy.controlled_drug_register'),
    ('trg_controlled_register_balance',     'pharmacy.controlled_drug_register'),
    ('trg_dispense_items_enforce',          'pharmacy.dispense_items'),
    ('trg_dispense_items_qty_uom',          'pharmacy.dispense_items'),
    ('trg_stock_ledger_qty_uom',            'inventory.stock_ledger'),
    ('trg_item_uoms_enforce',               'inventory.item_uoms'),
    ('trg_pur_grn_lines_enforce',           'inventory.pur_grn_lines'),
    ('trg_invoice_match_compute',           'inventory.pur_invoice_match_lines')
  ) AS t(name, tbl)
  WHERE NOT EXISTS (
    SELECT 1 FROM pg_trigger g
    JOIN pg_class c ON c.oid = g.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE g.tgname = t.name
      AND format('%s.%s', n.nspname, c.relname) = t.tbl
      AND NOT g.tgisinternal
  );

  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION 'Phase 4 migration did not attach these triggers: %', v_missing;
  END IF;
END
$$;

-- Prove the UoM guard and the ledger guard actually fire, inside the migration
-- that creates them. A guard nobody has exercised is a guard nobody knows works.
DO $$
DECLARE
  v_fired boolean := false;
BEGIN
  BEGIN
    PERFORM inventory.enforce_qty_uom();
  EXCEPTION
    WHEN feature_not_supported THEN v_fired := true;   -- called outside a trigger
    WHEN others THEN v_fired := true;
  END;

  IF NOT v_fired THEN
    RAISE EXCEPTION 'inventory.enforce_qty_uom() did not raise when called outside a trigger context; it is not the function this migration meant to create.';
  END IF;
END
$$;

-- ── 7. table comments: what an assessor reads first ────────────────────────
COMMENT ON TABLE inventory.stock_ledger IS
  'NC-006. The single source of truth for every quantity that has ever moved. Append-only and enforced four ways: a trigger that raises on UPDATE and DELETE, revoked UPDATE and DELETE privileges, partitions created by the append-only helper so next month inherits the guarantee, and a balance projection maintained only by this table''s own AFTER INSERT trigger. A mistaken row is corrected by a compensating row naming it (`corrects_ledger_id`) with a reason; the original stays, which is the point. Partitioned monthly on `moved_at` (timestamptz(3), D-31). `qty_base` is signed and always in the item''s base UoM, so sum() over any slice is that slice''s balance with no unit arithmetic anywhere.';
COMMENT ON TABLE inventory.stock_balances IS
  'A projection of the ledger, written by `inventory.apply_ledger_to_balance()` and by nothing else — which is what makes sum(ledger) = on_hand an invariant rather than a nightly reconciliation. `inventory.verify_stock_integrity()` re-derives it; phase-04 exit gate 6 runs that and requires an empty result.';
COMMENT ON TABLE inventory.items IS
  'NC-006 §4. The stock-keeping identity, distinct from `mdm.mdm_drugs`, which is the prescribable formulation: a doctor prescribes "Paracetamol 500 mg tablet" and a pharmacist hands over a strip of a brand from a batch. `drug_key` joins them and is null for the gauze, cannulae, reagents and implants that make up most of the master. `base_uom_id` is frozen once anything has moved — every historic qty_base is expressed in it.';
COMMENT ON TABLE inventory.item_uoms IS
  'The per-item conversion ladder — a strip is ten tablets for one brand and fifteen for another, so the factors cannot be global. Exactly one rung is the base, with factor 1; no rung crosses UoM dimensions, because no number converts millilitres to tablets. `inventory.enforce_qty_uom()` reads this table on every quantity written anywhere in the phase and refuses a row whose arithmetic disagrees, so a caller that forgets to convert gets an error naming the item rather than a balance that is wrong by a factor of ten.';
COMMENT ON TABLE inventory.item_batches IS
  'The unit a recall, an expiry and a traceability question all address; hospital-wide rather than per store, because the same batch sits in four stores and one recall must reach all of them. An expiry is mandatory for an expiry-tracked item — a batch with no expiry can never be blocked at dispensing, which is phase-04 exit gate 3 made impossible. MRP is checked against the DPCO ceiling in force on the receipt date, not today.';
COMMENT ON TABLE inventory.item_prices IS
  'Effective-dated and never retroactive (phase-04 §Constraints). An EXCLUDE constraint stops two prices covering one day; `inventory.refuse_retroactive_price()` stops a price being rewritten under a bill that already used it. A price is superseded by the next row, never edited. MRP is not here — it is printed on the pack and lives on the batch.';
COMMENT ON TABLE inventory.pur_vendor_invoices IS
  'NC-005 §4. `match_status` is the stored verdict of the three-way comparison, rolled up from `pur_invoice_match_lines` by trigger against the tolerances in `pur_settings`. The exception queue is `WHERE match_status <> ''matched''`, which is one index — and the reason a line failed is a column rather than a recomputation that may disagree with what the buyer saw. A missing settings row means zero tolerance, so every difference becomes an exception.';
COMMENT ON TABLE inventory.pur_grn_lines IS
  'Where a batch and an expiry enter the system, and therefore where they are made mandatory. Three quantities — received, accepted, rejected — because a partial receipt with a rejection is the ordinary case and a single qty column forces the truth into a remarks field. Refuses already-expired stock, stock with less shelf life than the item requires, and a scheduled drug from a vendor with no live drug licence.';
COMMENT ON TABLE inventory.csn_usages IS
  'NC-007. The implant went in. Billing, the auto-PO, the vendor statement and the TR-003 patient-implant register all hang off this row, and it is never deleted — a mistaken scan is reversed by a row naming what it reverses, because the implant was in the patient or it was not. The batch it names must be consignment stock; consuming owned stock through this path would invoice the vendor for something already paid for.';
COMMENT ON TABLE pharmacy.controlled_drug_register IS
  'The Schedule H1, Schedule X and NDPS registers, in one table with a `register_type`, because the columns are the same and three tables would be three places to forget the same rule. Append-only (trigger AND revoked privileges), gapless per store/register/financial year, and balanced by the database: `balance_after_base` is computed from the previous entry under a per-register advisory lock, never supplied, so two pharmacists issuing from one safe in the same second cannot produce two entries claiming the same balance. NDPS entries require a second authoriser who is not the first — docs/04 §1, phase-04 exit gate 4.';
COMMENT ON TABLE pharmacy.controlled_substance_limits IS
  'The limits that are actually real. Chapters VA and VB of the NDPS Rules 1985 (inserted by G.S.R. 359(E) of 5 May 2015) contain NO maximum duration and NO maximum quantity per patient for an Essential Narcotic Drug — rule 52U caps institutional holding against the Form 3J estimate and rule 52G(i) delegates the period to the prescriber. What is a hard number is rule 66(2): 100 dosage units of a psychotropic for personal medical use, 300 where specifically prescribed for long-term use, which binds Schedule X and the psychotropic H1 drugs and not the ENDs. `basis` separates statutory from policy and a hospital may not author or relax a statutory row. Inventing a seven-day opioid ceiling here would quietly rebuild the pre-2015 regime that cut India''s morphine consumption by ~92 %.';
COMMENT ON TABLE pharmacy.narcotic_custody_checks IS
