CREATE OR REPLACE FUNCTION pharmacy.enforce_dispense_line()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_dispense    record;
  v_tracking    "inventory"."InvTracking";
  v_schedule    "mdm"."MdmDrugSchedule";
  v_item_code   text;
  v_item_name   text;
  v_licence_to  date;
  v_ndps_to     date;
BEGIN
  SELECT d.dispense_type, d.prescription_id, d.prescriber_reg_no, d.pharmacy_store_id,
         d.pharmacist_user_id, d.second_auth_user_id, d.dispensed_at
    INTO v_dispense
  FROM pharmacy.dispenses d WHERE d.id = NEW.dispense_id;

  IF v_dispense IS NULL THEN
    RAISE EXCEPTION 'pharmacy.dispense_items: dispense % does not exist', NEW.dispense_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  SELECT i.tracking, i.schedule, i.code, i.name
    INTO v_tracking, v_schedule, v_item_code, v_item_name
  FROM inventory.items i WHERE i.id = NEW.item_id;

  IF v_item_code IS NULL THEN
    RAISE EXCEPTION 'pharmacy.dispense_items: item % does not exist', NEW.item_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  -- A declined line moves nothing and needs no batch. Everything else does.
  IF NEW.status NOT IN ('declined', 'cancelled', 'backordered')
     AND v_tracking IN ('batch', 'batch_expiry', 'udi')
     AND NEW.batch_id IS NULL
  THEN
    RAISE EXCEPTION
      'pharmacy.dispense_items: % is batch-tracked and this line names no batch. phase-04 §Constraints: never dispense without a successful batch validation.',
      v_item_code
      USING ERRCODE = 'check_violation';
  END IF;

  -- ── Schedule H over the counter — exit gate 3 ───────────────────────────
  IF v_dispense.dispense_type = 'otc'
     AND v_schedule IN ('h', 'h1', 'x', 'ndps_narcotic', 'ndps_psychotropic')
  THEN
    RAISE EXCEPTION
      '% is a Schedule % drug and cannot be sold over the counter. Rule 65(9)(a) of the Drugs and Cosmetics Rules 1945 permits retail sale of a Schedule H, H1 or X substance only against the prescription of a registered medical practitioner. Record the prescription on the dispense.',
      v_item_name, upper(v_schedule::text)
      USING ERRCODE = 'check_violation';
  END IF;

  -- A Schedule X or NDPS line needs the prescriber's registration number on the
  -- dispense, whether the prescription is internal or brought in on paper.
  IF v_schedule IN ('x', 'ndps_narcotic', 'ndps_psychotropic')
     AND (v_dispense.prescriber_reg_no IS NULL OR length(btrim(v_dispense.prescriber_reg_no)) = 0)
     AND v_dispense.prescription_id IS NULL
  THEN
    RAISE EXCEPTION
      '% is a Schedule % drug: the dispense must carry the prescriber''s registration number or reference an internal prescription. A controlled dispense with no traceable prescriber is the situation the register exists to prevent.',
      v_item_name, upper(v_schedule::text)
      USING ERRCODE = 'check_violation';
  END IF;

  -- ── the licence ─────────────────────────────────────────────────────────
  SELECT p.licence_valid_to, p.ndps_licence_valid_to INTO v_licence_to, v_ndps_to
  FROM pharmacy.pharmacy_stores p WHERE p.id = v_dispense.pharmacy_store_id;

  IF v_schedule IN ('h', 'h1', 'x', 'ndps_narcotic', 'ndps_psychotropic')
     AND (v_licence_to IS NULL OR v_licence_to < current_date)
  THEN
    RAISE EXCEPTION
      'This counter has no valid drug licence (Form 20/21) on record, so it may not dispense the Schedule % drug %.',
      upper(v_schedule::text), v_item_name
      USING ERRCODE = 'check_violation';
  END IF;

  IF v_schedule IN ('ndps_narcotic', 'ndps_psychotropic')
     AND (v_ndps_to IS NULL OR v_ndps_to < current_date)
  THEN
    RAISE EXCEPTION
      'This counter has no valid NDPS recognition on record, so it may not dispense %. NDPS Rules 1985 r.52Q: only a Recognised Medical Institution may dispense an essential narcotic drug.',
      v_item_name
      USING ERRCODE = 'check_violation';
  END IF;

  -- ── dual authorisation on the dispense as a whole ───────────────────────
  IF v_schedule IN ('ndps_narcotic', 'ndps_psychotropic')
     AND (v_dispense.second_auth_user_id IS NULL
          OR v_dispense.second_auth_user_id = v_dispense.pharmacist_user_id)
  THEN
    RAISE EXCEPTION
      '% is a controlled drug: the dispense needs a second authorising pharmacist, different from the first (docs/04 §1, phase-04 exit gate 4). Two signatures from one person are one signature.',
      v_item_name
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

