-- §D. GRANTS AND APPEND-ONLY ENFORCEMENT
--
-- `ALTER DEFAULT PRIVILEGES` from ..._grants already gave `hms_app` full DML and
-- `hms_readonly` SELECT on everything created here by `hms_migrator`. The
-- statements below are therefore (a) belt and braces for a deployment where the
-- migration ran as a different owner, and (b) the exceptions — stated one by one,
-- because an exception that is generated is an exception nobody reviews.
-- ═════════════════════════════════════════════════════════════════════════════

-- Deliberately NOT `GRANT ... ON ALL TABLES`. That form re-grants UPDATE and
-- DELETE on `core.audit_log`, `core.login_audit` and
-- `core.org_cross_branch_access_log`, silently undoing the append-only
-- guarantee ..._grants established — `verify-isolation.sql` case 4 catches it,
-- which is how this was found. Granting only where nothing is granted yet is
-- idempotent, covers every table this migration adds, and cannot reach a table
-- whose privileges were deliberately narrowed.
DO $$
DECLARE
  r record;
  v_count int := 0;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name, c.oid
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('core', 'mdm', 'integration')
      AND c.relkind IN ('r', 'p')
      AND c.relispartition = false
      AND c.relname NOT LIKE '\_prisma%'
      AND NOT has_table_privilege('hms_app', c.oid, 'SELECT')
  LOOP
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I.%I TO hms_app', r.schema_name, r.table_name);
    EXECUTE format('GRANT SELECT ON %I.%I TO hms_readonly', r.schema_name, r.table_name);
    v_count := v_count + 1;
  END LOOP;
  RAISE NOTICE 'Granted application DML on % previously ungranted table(s)', v_count;
END
$$;

