-- §C. CONSTRAINTS AND INDEXES THE SPECS REQUIRE STRUCTURALLY
--
-- Each of these encodes a rule a spec states as non-negotiable. They are
-- constraints rather than service checks because a service check is one code
-- path away from not happening.
-- ═════════════════════════════════════════════════════════════════════════════

-- EN-027 §5: "Effective ranges per `record_key` must not overlap (enforced by a
-- btree_gist exclusion constraint, not just application code)." This is the
-- reference implementation every later master copies — it is what makes
-- resolving "the department as it was on 3 April 2024" a single unambiguous row.
ALTER TABLE mdm.mdm_departments
  ADD CONSTRAINT mdm_departments_no_overlap
  EXCLUDE USING gist (
    record_key WITH =,
    tstzrange(effective_from, COALESCE(effective_to, 'infinity'::timestamptz)) WITH &&
  ) WHERE (status IN ('active', 'superseded'));

-- EN-037 §5: "Snooze is bounded (≤8 h), never available for `critical`."
-- `MAX_SNOOZE_SECONDS` in packages/contracts is the same 8 hours; this is the
-- half of the rule the database can hold.
ALTER TABLE core.notif_snoozes
  ADD CONSTRAINT notif_snoozes_bounded
  CHECK (until <= created_at + interval '8 hours');

-- EN-037 §3.1: an acknowledgement window only means anything on a type that
-- requires acknowledgement, and a type that requires one must declare it.
ALTER TABLE core.notif_types
  ADD CONSTRAINT notif_types_ack_window
  CHECK (NOT must_acknowledge OR ack_window_sec IS NOT NULL);

-- EN-038 §5: "a quorum stage cannot be configured with N > M".
ALTER TABLE core.wf_stages
  ADD CONSTRAINT wf_stages_quorum_arithmetic
  CHECK (quorum_n IS NULL OR (quorum_n > 0 AND quorum_n <= required_count));

-- EN-038 §5: "Requester ≠ approver, always." Maker-checker is structural.
ALTER TABLE core.wf_delegations
  ADD CONSTRAINT wf_delegations_distinct_parties
  CHECK (delegator_user_id <> delegate_user_id);

-- EN-040 §3.5: the degradation ladder has exactly five tiers (0–4).
ALTER TABLE core.lic_subscriptions
  ADD CONSTRAINT lic_subscriptions_degrade_tier_range
  CHECK (degrade_tier BETWEEN 0 AND 4);

-- EN-040 §5: "Invoices are gapless and immutable once issued"; the arithmetic
-- must hold before it is issued, not be discovered by a customer.
ALTER TABLE core.lic_invoices
  ADD CONSTRAINT lic_invoices_totals_non_negative
  CHECK (subtotal >= 0 AND discount >= 0 AND taxable_value >= 0
         AND cgst >= 0 AND sgst >= 0 AND igst >= 0 AND total >= 0);

-- EN-018 §5: "a widget with `phi_level=identifiable` cannot be placed on a board
-- whose location is marked public". The board half of that rule: a public board
-- may never be switched to full names without changing its privacy marking.
ALTER TABLE core.display_boards
  ADD CONSTRAINT display_boards_public_masking
  CHECK (location_privacy <> 'public' OR mask_mode <> 'full_name');

-- EN-018 §5: pairing codes are single-use and valid ten minutes.
ALTER TABLE core.display_devices
  ADD CONSTRAINT display_devices_pairing_window
  CHECK (pairing_code IS NULL OR pairing_expires_at IS NOT NULL);

