-- §A. MONTHLY PARTITIONS
--
-- `core.ensure_month_partition()` (defined in ..._partitions_and_indexes and
-- extended in ..._rls_policies) creates one month, enables RLS on it, attaches
-- the tenant policies and grants — so a partition created by the worker in 2029
-- is protected exactly like one created here.
--
-- Premake the current month, three ahead, and one behind: a back-dated entry
-- from the downtime protocol (docs/01 §7) must have somewhere to land.
-- ═════════════════════════════════════════════════════════════════════════════
DO $$
DECLARE
  v_tables text[][] := ARRAY[
    ['core', 'notif_notifications'],
    ['core', 'notif_deliveries'],
    ['core', 'wf_requests'],
    ['core', 'wf_actions'],
    ['core', 'tpl_render_jobs'],
    ['core', 'lic_usage_daily'],
    ['core', 'print_jobs'],
    ['core', 'sso_login_attempts'],
    ['core', 'sso_scim_operations'],
    ['core', 'bc_scan_events'],
    ['core', 'display_device_events'],
    ['integration', 'ihub_messages']
  ];
  i int;
  m int;
BEGIN
  FOR i IN 1 .. array_length(v_tables, 1) LOOP
    FOR m IN -1 .. 3 LOOP
      PERFORM core.ensure_month_partition(
        v_tables[i][1],
        v_tables[i][2],
        (date_trunc('month', now()) + (m || ' month')::interval)::date
      );
    END LOOP;
  END LOOP;
END
$$;

-- ── DEFAULT partitions ───────────────────────────────────────────────────────
-- Without one, an INSERT whose timestamp falls outside every declared range
-- fails. For `notif_notifications` that failure would swallow a critical-value
-- alert; for `wf_actions` it would roll back the approval that triggered it.
-- A default partition turns a missed maintenance run from a clinical incident
-- into a monitored anomaly (a non-empty default partition is alertable, never
-- normal). Unlike the parents, a default partition is queried directly by
-- support tooling, so it gets its own RLS and grants.
DO $$
DECLARE
  v_tables text[][] := ARRAY[
    ['core', 'notif_notifications'],
    ['core', 'notif_deliveries'],
    ['core', 'wf_requests'],
    ['core', 'wf_actions'],
    ['core', 'tpl_render_jobs'],
    ['core', 'lic_usage_daily'],
    ['core', 'print_jobs'],
    ['core', 'sso_login_attempts'],
    ['core', 'sso_scim_operations'],
    ['core', 'bc_scan_events'],
    ['core', 'display_device_events'],
    ['integration', 'ihub_messages']
  ];
  i int;
  v_schema     text;
  v_table      text;
  v_default    text;
  v_qualified  text;
  v_using      text;
  v_has_branch boolean;
BEGIN
  FOR i IN 1 .. array_length(v_tables, 1) LOOP
    v_schema  := v_tables[i][1];
    v_table   := v_tables[i][2];
    v_default := v_table || '_default';
    v_qualified := format('%I.%I', v_schema, v_default);

    IF NOT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = v_schema AND c.relname = v_default
    ) THEN
      EXECUTE format('CREATE TABLE %s PARTITION OF %I.%I DEFAULT', v_qualified, v_schema, v_table);
    END IF;

    SELECT count(*) FILTER (WHERE column_name = 'branch_id') > 0
    INTO v_has_branch
    FROM information_schema.columns
    WHERE table_schema = v_schema AND table_name = v_table;

    v_using := 'hospital_id = ANY (core.accessible_hospital_ids())';
    IF v_has_branch THEN
      v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
    END IF;

    EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', v_qualified);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %s', v_qualified);
    EXECUTE format('CREATE POLICY tenant_isolation ON %s FOR ALL TO hms_app USING (%s) WITH CHECK (%s)',
                   v_qualified, v_using, v_using);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_ro ON %s', v_qualified);
    EXECUTE format('CREATE POLICY tenant_isolation_ro ON %s FOR SELECT TO hms_readonly USING (%s)',
                   v_qualified, v_using);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %s TO hms_app', v_qualified);
    EXECUTE format('GRANT SELECT ON %s TO hms_readonly', v_qualified);

    EXECUTE format(
      'COMMENT ON TABLE %s IS %L',
      v_qualified,
      'Safety net only. A non-empty default partition is an alertable anomaly (docs/07 §6), never a normal state.'
    );
  END LOOP;
END
$$;


-- ═════════════════════════════════════════════════════════════════════════════
-- §B. ROW-LEVEL SECURITY
--
-- The generator from ..._rls_policies ran against the 48 tables that existed
-- then. It is re-run here, narrowed to tables that do **not** already carry a
-- `tenant_isolation` policy, for two reasons:
--
--   1. It must not clobber the three explicit policies added by
--      ..._rls_tenant_key_exceptions (`core.hospitals`, `core.org_groups`,
--      `core.role_permissions`), whose tenant key is not `hospital_id`.
--      Re-running the unfiltered generator would silently reopen the
--      cross-tenant metadata leak that migration exists to close.
--   2. Deriving the policy from the columns rather than listing 124 tables by
--      hand is what makes it impossible to forget one — the property that
--      caught the original defect.
--
-- Classification is unchanged: `hospital_id NOT NULL` → tenant-scoped;
-- `hospital_id NULL`-able → mixed (system rows readable, only own rows
-- writable); no tenant column → global catalogue, handled explicitly below.
-- ═════════════════════════════════════════════════════════════════════════════
DO $$
DECLARE
  r                record;
  v_has_hospital   boolean;
  v_hospital_null  boolean;
  v_has_branch     boolean;
  v_using          text;
  v_check          text;
  v_count          int := 0;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('core', 'mdm', 'integration')
      AND c.relkind IN ('r', 'p')
      AND c.relispartition = false
      AND c.relname NOT LIKE '\_prisma%'
      AND NOT EXISTS (
        SELECT 1 FROM pg_policy p
        WHERE p.polrelid = c.oid AND p.polname = 'tenant_isolation'
      )
    ORDER BY n.nspname, c.relname
  LOOP
    SELECT
      count(*) FILTER (WHERE column_name = 'hospital_id') > 0,
      bool_or(column_name = 'hospital_id' AND is_nullable = 'YES'),
      count(*) FILTER (WHERE column_name = 'branch_id') > 0
    INTO v_has_hospital, v_hospital_null, v_has_branch
    FROM information_schema.columns
    WHERE table_schema = r.schema_name AND table_name = r.table_name;

    EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', r.schema_name, r.table_name);

    IF v_has_hospital AND NOT v_hospital_null THEN
      v_using := 'hospital_id = ANY (core.accessible_hospital_ids())';
      IF v_has_branch THEN
        v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;
      v_check := v_using;

    ELSIF v_has_hospital AND v_hospital_null THEN
      -- System catalogue rows (a shipped notification type, a system form
      -- template, a default barcode scheme) are readable by every tenant and
      -- writable by none of them through the application role.
      v_using := '(hospital_id IS NULL OR hospital_id = ANY (core.accessible_hospital_ids()))';
      IF v_has_branch THEN
        v_using := v_using || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;
      v_check := 'hospital_id = ANY (core.accessible_hospital_ids())';
      IF v_has_branch THEN
        v_check := v_check || ' AND (branch_id IS NULL OR branch_id = ANY (core.current_branch_ids()))';
      END IF;

    ELSE
      -- Deliberately NOT `USING (true)`. See the explicit block below; this
      -- placeholder denies everything so a table that slipped past the explicit
      -- list fails loudly at first use rather than leaking quietly.
      v_using := 'false';
      v_check := 'false';
    END IF;

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I.%I FOR ALL TO hms_app USING (%s) WITH CHECK (%s)',
      r.schema_name, r.table_name, v_using, v_check
    );

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_ro ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation_ro ON %I.%I FOR SELECT TO hms_readonly USING (%s)',
      r.schema_name, r.table_name, v_using
    );

    v_count := v_count + 1;
  END LOOP;

  RAISE NOTICE 'Row-level security enabled with tenant policies on % new tables', v_count;
END
$$;

-- ── global catalogues: readable only *with* a tenant context ─────────────────
-- Ten of the new tables have no tenant column, for the same reason
-- `core.permissions` has none: they are byte-identical for every tenant and are
-- read on nearly every request.
--
--   core.lic_plans / core.lic_plan_versions   — the operator's price book
--                                               (EN-040 §4: "operator-scoped
--                                               tables live in the control
--                                               plane"); a hospital must see
--                                               the plan it is on and the plan
--                                               it could move to.
--   core.lic_enforcement_points               — synced from packages/contracts;
--                                               the registry the safety suite
--                                               asserts `clinical_safety_exempt`
--                                               against.
--   core.display_widgets_catalogue            — EN-018 §4 "seed, code-registered".
--   integration.ihub_connector_packages       — signed adapter packages.
--   mdm.mdm_masters_registry                  — product metadata about masters.
--   mdm.mdm_code_systems / mdm_concepts /
--   mdm_concept_closure / mdm_concept_designations
--                                             — ICD, LOINC, SNOMED, ATC, UCUM.
--                                               Licensed terminology, not tenant
--                                               data. Scoping ICD-11 per
--                                               hospital would store 120 000
--                                               identical concepts per tenant.
--
-- They are NOT given `USING (true)`. The predicate below requires a session to
-- have established a tenant context at all, which means the default-deny
-- property of `current_setting(..., true)` still holds: a connection that never
-- ran `SET LOCAL app.hospital_id` reads nothing, anywhere. That is strictly
-- stronger than the two pre-existing `USING (true)` catalogues, and it keeps
-- `core.v_rls_open_policies` at exactly {permissions, setting_definitions} —
-- the list `verify-isolation.sql` case 2 asserts.
--
-- Writes go to nobody through `hms_app`: these are loader/seed-owned tables and
-- the migration role owns them.
DO $$
DECLARE
  r record;
  v_using text := 'cardinality(core.accessible_hospital_ids()) > 0';
BEGIN
  FOR r IN
    SELECT * FROM (VALUES
      ('core', 'lic_plans'),
      ('core', 'lic_plan_versions'),
      ('core', 'lic_enforcement_points'),
      ('core', 'display_widgets_catalogue'),
      ('integration', 'ihub_connector_packages'),
      ('mdm', 'mdm_masters_registry'),
      ('mdm', 'mdm_code_systems'),
      ('mdm', 'mdm_concepts'),
      ('mdm', 'mdm_concept_closure'),
      ('mdm', 'mdm_concept_designations')
    ) AS t(schema_name, table_name)
  LOOP
    EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', r.schema_name, r.table_name);

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I.%I FOR ALL TO hms_app USING (%s) WITH CHECK (false)',
      r.schema_name, r.table_name, v_using
    );

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation_ro ON %I.%I', r.schema_name, r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation_ro ON %I.%I FOR SELECT TO hms_readonly USING (%s)',
      r.schema_name, r.table_name, v_using
    );
  END LOOP;
END
$$;


