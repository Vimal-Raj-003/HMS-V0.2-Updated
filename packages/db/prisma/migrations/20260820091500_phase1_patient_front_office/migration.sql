-- ── C.9 the five patient-search paths ───────────────────────────────────────
--
-- `phase-01 §1.2`: "Search that is actually fast: mobile / UHID / name / ABHA /
-- ID, trigram + prefix indexes, ≤ 200 ms p95 on 1 M patients."
--
-- Five paths, five strategies. The composite btree indexes lead with
-- `hospital_id` per docs/03 §Table rules, which also makes them usable for the
-- RLS predicate itself. The trigram GIN indexes cannot lead with `hospital_id`
-- — that would need `btree_gin`, which is not in the extension matrix — so they
-- index the text alone and the planner applies the tenant predicate as a
-- recheck on the handful of rows a trigram match returns. That is exactly the
-- shape docs/07 §4 prescribes for `idx_patients_name_trgm`, and it is measured
-- rather than assumed: see the EXPLAIN evidence in `docs/PROGRESS.md`.
--
--   1. mobile   — exact on the E.164 form, prefix on the local form
--   2. UHID     — unique on the printed form, prefix and trigram on the
--                 normalised one (a receptionist types what they remember)
--   3. name     — trigram on `full_name`
--   4. ABHA     — partial btree on the denormalised column, unique on the
--                 identifier row
--   5. govt ID  — btree on the normalised identifier value

-- 1. mobile.
CREATE INDEX IF NOT EXISTS idx_patients_mobile_prefix
  ON patient.patients (hospital_id, mobile_local varchar_pattern_ops);
CREATE INDEX IF NOT EXISTS idx_patients_mobile_trgm
  ON patient.patients USING gin (mobile_local ext.gin_trgm_ops);
-- OP-001 §5: "Mobile may be shared across family (max N=10 per mobile
-- configurable; warn beyond)" — so this is emphatically NOT unique. It is the
-- index that makes "who else uses this number?" instant.

-- 2. UHID.
CREATE INDEX IF NOT EXISTS idx_patients_uhid_prefix
  ON patient.patients (hospital_id, uhid_normalised varchar_pattern_ops);
CREATE INDEX IF NOT EXISTS idx_patients_uhid_trgm
  ON patient.patients USING gin (uhid_normalised ext.gin_trgm_ops);

-- 3. name. `docs/07 §4` names this index explicitly.
CREATE INDEX IF NOT EXISTS idx_patients_name_trgm
  ON patient.patients USING gin (full_name ext.gin_trgm_ops);
-- The local-script name, for a hospital that captures Tamil or Devanagari.
CREATE INDEX IF NOT EXISTS idx_patients_local_name_trgm
  ON patient.patients USING gin (local_name ext.gin_trgm_ops)
  WHERE local_name IS NOT NULL;

-- 4. ABHA. Partial, because only a minority of patients have one and the index
-- should stay the size of that minority rather than of the MPI.
CREATE INDEX IF NOT EXISTS idx_patients_abha_number
  ON patient.patients (hospital_id, abha_number)
  WHERE abha_number IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_patients_abha_address
  ON patient.patients (hospital_id, abha_address)
  WHERE abha_address IS NOT NULL;

-- 5. government ID, and every other identifier type, through one index.
CREATE INDEX IF NOT EXISTS idx_identifiers_value_prefix
  ON patient.identifiers (hospital_id, value_normalised varchar_pattern_ops)
  WHERE deleted_at IS NULL;

-- The two rules OP-001 §5 scores at 0.9 and 1.0. A deterministic duplicate is
-- found by an index probe before any trigram work happens, which is what keeps
-- duplicate detection inside the 400 ms registration budget.
CREATE INDEX IF NOT EXISTS idx_patients_aadhaar_hash
  ON patient.patients (hospital_id, aadhaar_hash)
  WHERE aadhaar_hash IS NOT NULL;

-- The recent-patients list (OP-001 §1.2) and the default sort of every patient
-- worklist: `(hospital_id, created_at desc)` per docs/03 §Performance rules,
-- with `id` as the cursor tiebreaker.
CREATE INDEX IF NOT EXISTS idx_patients_cursor
  ON patient.patients (hospital_id, created_at DESC, id DESC);

-- Active records only. Merged, blocked and inactive rows are a small and
-- growing minority that no search screen wants, and excluding them keeps the
-- index the size of the working set rather than of the history.
CREATE INDEX IF NOT EXISTS idx_patients_active_name_trgm
  ON patient.patients USING gin (full_name ext.gin_trgm_ops)
  WHERE status = 'active' AND deleted_at IS NULL;

