-- §B. ROW-LEVEL SECURITY
--
-- Phase 1 is the first migration to add a *schema*, and that is the dangerous
-- part. `core.v_rls_coverage`, `core.v_rls_open_policies` and
-- `core.v_grant_coverage` were written against `('core', 'mdm', 'integration')`
-- because those were the only schemas that existed. Ninety-three new tables in
-- `patient`, `clinical`, `queue`, `engage` and `billing` would therefore have
-- been *invisible* to the monitor that exists to catch exactly this — the
-- integration suite would have gone on reporting "zero unprotected tables"
-- while the patient master sat wide open.
--
-- So the views are widened first, before a single policy is written. That
-- ordering is deliberate: if the generator below were to miss a table, the
-- widened view is what fails the build.
-- ═════════════════════════════════════════════════════════════════════════════

-- ── 1. widen the coverage monitors to the schemas that now exist ─────────────
CREATE OR REPLACE VIEW core.v_rls_coverage AS
SELECT
  n.nspname                                        AS schema_name,
  c.relname                                        AS table_name,
  c.relrowsecurity                                 AS rls_enabled,
  c.relforcerowsecurity                            AS rls_forced,
  count(p.polname) FILTER (WHERE p.polname IS NOT NULL) AS policy_count,
  bool_or(p.polname = 'tenant_isolation')          AS has_tenant_policy,
  bool_or(p.polname = 'tenant_isolation' AND p.polwithcheck IS NOT NULL) AS has_write_check,
  EXISTS (
    SELECT 1 FROM information_schema.columns col
    WHERE col.table_schema = n.nspname AND col.table_name = c.relname
      AND col.column_name = 'hospital_id'
  )                                                AS is_tenant_scoped
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_policy p ON p.polrelid = c.oid
WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration')
  AND c.relkind IN ('r', 'p')
  AND c.relispartition = false
  AND c.relname NOT LIKE '\_prisma%'
GROUP BY n.nspname, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.oid;

COMMENT ON VIEW core.v_rls_coverage IS
  'One row per application table with its RLS status. `has_tenant_policy` false or `has_write_check` false on a tenant-scoped table is a release-blocking defect (docs/09 §3.1). The schema list must be widened by the migration that adds a schema — a table in a schema this view does not know about is unmonitored, not safe.';

GRANT SELECT ON core.v_rls_coverage TO hms_app, hms_readonly;

CREATE OR REPLACE VIEW core.v_rls_open_policies AS
SELECT
  n.nspname                          AS schema_name,
  c.relname                          AS table_name,
  p.polname                          AS policy_name,
  pg_get_expr(p.polqual, p.polrelid) AS using_expr,
  ARRAY(
    SELECT r.rolname FROM pg_roles r WHERE r.oid = ANY (p.polroles) ORDER BY r.rolname
  )                                  AS granted_to
FROM pg_policy p
JOIN pg_class c ON c.oid = p.polrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration')
  AND pg_get_expr(p.polqual, p.polrelid) = 'true'
  -- `hms_retention` is excluded by design; `hms_migrator` owns the tables and
  -- bypasses RLS anyway.
  AND EXISTS (
    SELECT 1 FROM pg_roles r
    WHERE r.oid = ANY (p.polroles) AND r.rolname IN ('hms_app', 'hms_readonly')
  );

COMMENT ON VIEW core.v_rls_open_policies IS
  'Policies granting unrestricted reads to a request-serving role (hms_app / hms_readonly). The integration suite asserts this equals exactly {permissions, setting_definitions}; anything else is a cross-tenant leak. hms_retention is deliberately excluded — it spans tenants to archive partitions and holds no privilege on business tables.';

GRANT SELECT ON core.v_rls_open_policies TO hms_app, hms_readonly;

CREATE OR REPLACE VIEW core.v_grant_coverage AS
SELECT
  t.table_schema,
  t.table_name,
  bool_or(g.privilege_type = 'SELECT' AND g.grantee = 'hms_app') AS app_can_select,
  bool_or(g.privilege_type = 'INSERT' AND g.grantee = 'hms_app') AS app_can_insert,
  bool_or(g.privilege_type = 'UPDATE' AND g.grantee = 'hms_app') AS app_can_update,
  bool_or(g.privilege_type = 'DELETE' AND g.grantee = 'hms_app') AS app_can_delete,
  bool_or(g.grantee = 'hms_readonly' AND g.privilege_type <> 'SELECT') AS readonly_has_write
FROM information_schema.tables t
LEFT JOIN information_schema.role_table_grants g
  ON g.table_schema = t.table_schema AND g.table_name = t.table_name
WHERE t.table_schema IN ('core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration')
  AND t.table_type = 'BASE TABLE'
GROUP BY t.table_schema, t.table_name;

COMMENT ON VIEW core.v_grant_coverage IS
  'Effective privileges per table. `readonly_has_write` true anywhere, or `app_can_update` true on core.audit_log, is a release-blocking defect (docs/04 §6, EN-024 §3.4.4).';

GRANT SELECT ON core.v_grant_coverage TO hms_app, hms_readonly;

