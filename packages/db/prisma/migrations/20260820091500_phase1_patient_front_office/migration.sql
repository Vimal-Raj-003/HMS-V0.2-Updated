-- ═════════════════════════════════════════════════════════════════════════════
-- §D. GRANTS AND APPEND-ONLY ENFORCEMENT
--
-- `ALTER DEFAULT PRIVILEGES` in §B.2 gave `hms_app` full DML and `hms_readonly`
-- SELECT on everything `hms_migrator` creates in the five new schemas from now
-- on — but it was set *after* Prisma had already created these 93 tables, so it
-- does not apply to them. The loop below is what actually grants them, and it
-- is deliberately narrowed to tables that hold no grant yet, for the same
-- reason as in Phase 0: `GRANT ... ON ALL TABLES` would silently re-grant
-- UPDATE and DELETE on the append-only tables and undo the guarantees below.
-- ═════════════════════════════════════════════════════════════════════════════
DO $$
DECLARE
  r record;
  v_count int := 0;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name, c.oid
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('core', 'mdm', 'patient', 'clinical', 'queue', 'engage', 'billing', 'integration')
      AND c.relkind IN ('r', 'p')
      AND c.relispartition = false
      AND c.relname NOT LIKE '\_prisma%'
      AND NOT has_table_privilege('hms_app', c.oid, 'SELECT')
  LOOP
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I.%I TO hms_app', r.schema_name, r.table_name);
    EXECUTE format('GRANT SELECT ON %I.%I TO hms_readonly', r.schema_name, r.table_name);
    v_count := v_count + 1;
  END LOOP;
  RAISE NOTICE 'Granted application DML on % previously ungranted table(s)', v_count;
END
$$;

