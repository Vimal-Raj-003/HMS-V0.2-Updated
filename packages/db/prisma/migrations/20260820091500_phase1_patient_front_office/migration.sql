-- ── C.12 keeping the allergy statement true ─────────────────────────────────
--
-- The statement and the entries can disagree, and the direction that matters is
-- the dangerous one: entries present while the statement still says
-- `not_recorded`. A trigger is preferred to application code here for the
-- reason `docs/03` gives for every other structural rule — a service check is
-- one code path away from not happening, and this particular code path is
-- reached from registration, the doctor's console, an ABDM import and a bulk
-- migration, which are four chances to forget.
--
-- The asymmetry is deliberate and is the whole point:
--
--   * an active entry appearing  →  `known`
--   * the last active entry going away  →  `not_recorded`, **never**
--     `none_known`. Deleting rows is not the same as asserting there are none.
--     A patient whose only recorded allergy is retracted as entered-in-error
--     has not been cleared; they have been returned to unasked.
--
-- A deliberate `none_known` or `unable_to_assess` is left alone: neither has
-- entries, so neither is contradicted by their absence.
CREATE OR REPLACE FUNCTION patient.recompute_allergy_statement(p_patient_id uuid)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  v_active      int;
  v_asserted_by uuid;
  v_asserted_at timestamptz;
BEGIN
  SELECT count(*) INTO v_active
  FROM patient.allergies a
  WHERE a.patient_id = p_patient_id AND a.status = 'active';

  IF v_active > 0 THEN
    SELECT a.recorded_by, a.recorded_at
    INTO v_asserted_by, v_asserted_at
    FROM patient.allergies a
    WHERE a.patient_id = p_patient_id AND a.status = 'active'
    ORDER BY a.recorded_at DESC, a.id DESC
    LIMIT 1;

    UPDATE patient.patients p
       SET allergy_statement    = 'known',
           -- Keep the original asserter when the patient was already `known`;
           -- the person who first established the allergy history is the one
           -- accountable for it, not whoever added the third entry.
           allergy_asserted_by  = COALESCE(p.allergy_asserted_by, v_asserted_by),
           allergy_asserted_at  = COALESCE(p.allergy_asserted_at, v_asserted_at),
           allergy_unable_reason = NULL
     WHERE p.id = p_patient_id
       AND p.allergy_statement IS DISTINCT FROM 'known';
  ELSE
    UPDATE patient.patients p
       SET allergy_statement     = 'not_recorded',
           allergy_asserted_by   = NULL,
           allergy_asserted_at   = NULL,
           allergy_unable_reason = NULL
     WHERE p.id = p_patient_id
       AND p.allergy_statement = 'known';
  END IF;
END;
$$;

COMMENT ON FUNCTION patient.recompute_allergy_statement IS
  'Reconciles patient.patients.allergy_statement with the active rows in patient.allergies. Promotes to `known`; demotes only to `not_recorded`. It can never produce `none_known` — that arm is a clinical assertion a person makes, not a fact derivable from an empty table.';

CREATE OR REPLACE FUNCTION patient.sync_allergy_statement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.patient_id IS DISTINCT FROM NEW.patient_id THEN
    PERFORM patient.recompute_allergy_statement(OLD.patient_id);
  END IF;
  PERFORM patient.recompute_allergy_statement(COALESCE(NEW.patient_id, OLD.patient_id));
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_allergies_sync_statement ON patient.allergies;
CREATE TRIGGER trg_allergies_sync_statement
  AFTER INSERT OR UPDATE OR DELETE ON patient.allergies
  FOR EACH ROW EXECUTE FUNCTION patient.sync_allergy_statement();

GRANT EXECUTE ON FUNCTION patient.recompute_allergy_statement(uuid) TO hms_app;

