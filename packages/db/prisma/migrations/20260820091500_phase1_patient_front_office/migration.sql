-- §C. CONSTRAINTS AND INDEXES THE SPECS REQUIRE STRUCTURALLY
--
-- Each of these encodes a rule a spec states as non-negotiable. They are
-- constraints rather than service checks because a service check is one code
-- path away from not happening — and because two API pods do not share a mutex,
-- but they do share a row lock.
