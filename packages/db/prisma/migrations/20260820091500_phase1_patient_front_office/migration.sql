-- ── C.1 the effective-dated masters ──────────────────────────────────────────
-- EN-027 §5: "Effective ranges per `record_key` must not overlap (enforced by a
-- btree_gist exclusion constraint, not just application code)." Phase 0 wrote
-- this once, by hand, for `mdm_departments`, as the reference implementation.
-- Thirteen masters now copy it. This is a loop rather than thirteen statements
-- because it is one rule applied uniformly, not thirteen exceptions — the
-- moment a master needs a *different* rule it leaves the list and is written
-- out in full.
DO $$
DECLARE
  v_tables text[] := ARRAY[
    'mdm_specialities', 'mdm_practitioners', 'mdm_consult_types', 'mdm_practitioner_fees',
    'mdm_services', 'mdm_rooms', 'mdm_id_types', 'mdm_relationship_types',
    'mdm_occupations', 'mdm_religions', 'mdm_areas', 'mdm_titles',
    'mdm_languages', 'mdm_nationalities', 'mdm_referral_sources'
  ];
  t text;
BEGIN
  FOREACH t IN ARRAY v_tables LOOP
    EXECUTE format(
      'ALTER TABLE mdm.%I ADD CONSTRAINT %I EXCLUDE USING gist ('
        || 'record_key WITH =, '
        || 'tstzrange(effective_from, COALESCE(effective_to, ''infinity''::timestamptz)) WITH &&'
        || ') WHERE (status IN (''active'', ''superseded''))',
      t, t || '_no_overlap'
    );
  END LOOP;
END
$$;

-- ── C.2 the patient record ───────────────────────────────────────────────────

-- OP-001 §4: `full_name` is described as generated. Prisma cannot express a
-- generated column and would propose to drop one it cannot see, so the
-- application composes it — and the database refuses a blank, which is the half
-- of the guarantee it can hold. A patient with no name is not a patient.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_full_name_present CHECK (length(btrim(full_name)) > 0);

-- OP-001 §3.1: mobile is E.164 with the country default. Registration is the
-- highest-traffic screen in the hospital and every downstream message, every
-- duplicate rule and every portal login keys off this column; a malformed
-- number here becomes an undeliverable OTP three modules away.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_mobile_e164 CHECK (mobile ~ '^\+[1-9][0-9]{6,14}$');

-- The Aadhaar Act, as a constraint. There is no column that can hold a full
-- Aadhaar number; what there is must be internally consistent — a hash without
-- the key version that produced it cannot be re-derived or rotated, and a
-- "last four" without a hash is an identifier fragment serving no purpose.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_aadhaar_hash_pairing
  CHECK ((aadhaar_hash IS NULL) = (aadhaar_hash_key_version IS NULL));
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_aadhaar_last4_shape
  CHECK (aadhaar_last4 IS NULL OR (aadhaar_last4 ~ '^[0-9]{4}$' AND aadhaar_hash IS NOT NULL));

-- ── the four-arm allergy statement (docs/06 §10, packages/ui AllergyEditor) ──
--
-- With per-entry rows alone, zero rows in `patient.allergies` is ambiguous
-- between "nobody has asked", "asked and could not establish" and "asked, the
-- patient says none". A prescriber reading the first as the third is how a
-- penicillin-allergic patient gets penicillin, so the statement is a column and
-- these are its two invariants.

-- 1. An "unable to assess" that does not say why is not actionable by the next
--    clinician — it is indistinguishable from nobody having tried.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_allergy_unable_reason
  CHECK (allergy_statement <> 'unable_to_assess' OR allergy_unable_reason IS NOT NULL);

-- 2. "None known" is a clinical assertion somebody is accountable for. An
--    assertion nobody signed is worth exactly as much as no assertion at all,
--    which is why all three non-default arms require an asserter and an
--    instant. `not_recorded` requires neither, and is the default, so a
--    backfilled row can never silently claim a clinician cleared the patient.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_allergy_assertion_attributed
  CHECK (
    allergy_statement = 'not_recorded'
    OR (allergy_asserted_by IS NOT NULL AND allergy_asserted_at IS NOT NULL)
  );

-- 3. Only `unable_to_assess` may carry a reason, so the column cannot become a
--    second, contradictory note on a `known` record.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_allergy_reason_scoped
  CHECK (allergy_statement = 'unable_to_assess' OR allergy_unable_reason IS NULL);

-- OP-001 §5: age-only capture is legitimate; an age with no basis is not.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_age_basis
  CHECK (dob IS NOT NULL OR age_years IS NOT NULL OR age_months IS NOT NULL OR age_days IS NOT NULL);

-- A deceased flag with no instant cannot be reported on, and an instant with no
-- flag will not reach the banner. NABH and the death register need both.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_deceased_pairing
  CHECK (is_deceased = false OR deceased_at IS NOT NULL);

-- OP-001 §3.8: a merged record must say what it merged into, and an unmerged
-- one must not pretend to. This is what makes "follow `merged_into_id`" a rule
-- a consumer can trust rather than a convention it must test for.
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_merge_pairing
  CHECK ((status = 'merged') = (merged_into_id IS NOT NULL));
ALTER TABLE patient.patients
  ADD CONSTRAINT patients_merge_not_self
  CHECK (merged_into_id IS NULL OR merged_into_id <> id);

-- A dedupe candidate is a pair of two different records, stored in one
-- canonical order so (A,B) and (B,A) cannot both exist as "open".
ALTER TABLE patient.dedupe_candidates
  ADD CONSTRAINT dedupe_candidates_ordered_pair
  CHECK (patient_a_id < patient_b_id);
ALTER TABLE patient.dedupe_candidates
  ADD CONSTRAINT dedupe_candidates_score_range
  CHECK (score >= 0 AND score <= 1);

-- OP-001 §3.8 / §5: a merge has two distinct parties and a bounded reversal
-- window. "Unmerge within 30 days" is only a promise if the deadline is stored.
ALTER TABLE patient.merges
  ADD CONSTRAINT merges_distinct_parties CHECK (survivor_id <> victim_id);
ALTER TABLE patient.merges
  ADD CONSTRAINT merges_unmerge_window CHECK (unmerge_deadline > requested_at);

-- A relationship is between two people.
ALTER TABLE patient.relationships
  ADD CONSTRAINT relationships_distinct_parties CHECK (patient_id <> related_patient_id);

-- ── C.3 consent ─────────────────────────────────────────────────────────────

