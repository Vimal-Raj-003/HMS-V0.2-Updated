-- ── C.4 schedules, slots and appointments ───────────────────────────────────

ALTER TABLE clinical.doctor_schedule_templates
  ADD CONSTRAINT doctor_schedule_templates_weekday CHECK (weekday BETWEEN 1 AND 7);
ALTER TABLE clinical.doctor_schedule_templates
  ADD CONSTRAINT doctor_schedule_templates_time_order CHECK (end_time > start_time);
ALTER TABLE clinical.doctor_schedule_templates
  ADD CONSTRAINT doctor_schedule_templates_slot_minutes CHECK (slot_minutes BETWEEN 1 AND 480);
ALTER TABLE clinical.doctor_schedule_templates
  ADD CONSTRAINT doctor_schedule_templates_quota CHECK (online_quota_pct BETWEEN 0 AND 100);
ALTER TABLE clinical.doctor_schedule_templates
  ADD CONSTRAINT doctor_schedule_templates_capacity CHECK (capacity_per_slot >= 1 AND overbook_allowance >= 0);

ALTER TABLE clinical.schedule_exceptions
  ADD CONSTRAINT schedule_exceptions_time_order CHECK (ends_at > starts_at);

-- OP-001 §14 AC-4 and AC-5, as a constraint rather than a service check: a
-- third booking into a two-place slot fails, and two receptionists racing for
-- the last place produce exactly one winner because the loser's UPDATE violates
-- this after taking the row lock. Overbooking is not "ignore the limit" — it is
-- a larger, explicitly configured limit that a privileged user may reach.
ALTER TABLE clinical.schedule_slots
  ADD CONSTRAINT schedule_slots_capacity
  CHECK (booked_count >= 0 AND booked_count <= capacity + overbook_allowance);
ALTER TABLE clinical.schedule_slots
  ADD CONSTRAINT schedule_slots_online_quota
  CHECK (online_booked_count >= 0 AND online_booked_count <= booked_count);
ALTER TABLE clinical.schedule_slots
  ADD CONSTRAINT schedule_slots_time_order CHECK (slot_end > slot_start);

-- OP-001 §4: "Exclusion via `btree_gist` on (doctor_id, tstzrange(slot_start,
-- slot_end)) when capacity=1." A one-place clinic slot cannot overlap another
-- one-place slot for the same doctor — a doctor cannot be in two rooms at once,
-- and a template edit that would put them there is rejected at write time
-- rather than discovered by two patients in a corridor.
ALTER TABLE clinical.schedule_slots
  ADD CONSTRAINT schedule_slots_no_overlap
  EXCLUDE USING gist (
    practitioner_key WITH =,
    tstzrange(slot_start, slot_end) WITH &&
  ) WHERE (capacity = 1 AND status <> 'cancelled');

ALTER TABLE clinical.appointments
  ADD CONSTRAINT appointments_time_order CHECK (slot_end > slot_start);

-- OP-001 §4: an appointment is for a registered patient or for a lead with a
-- name and a number. It is never for nobody.
ALTER TABLE clinical.appointments
  ADD CONSTRAINT appointments_subject
  CHECK (patient_id IS NOT NULL OR (lead_name IS NOT NULL AND lead_mobile IS NOT NULL));

-- OP-001 §5: overbooking requires the `appointment.overbook` permission, and
-- the approver is recorded. A flag with no approver is an unaudited exception.
ALTER TABLE clinical.appointments
  ADD CONSTRAINT appointments_overbook_approver
  CHECK (is_overbooked = false OR overbook_approved_by IS NOT NULL);

-- OP-001 §3.4.5: cancellation carries a reason, always.
ALTER TABLE clinical.appointments
  ADD CONSTRAINT appointments_cancel_reason
  CHECK (status <> 'cancelled' OR cancel_reason IS NOT NULL);

-- OP-001 §5: "same patient same doctor same day duplicate blocked". Partial
-- unique on the live states only, so a cancelled booking never blocks a rebook.
-- `slot_date` is a stored column rather than `slot_start::date` because casting
-- a timestamptz to a date depends on the session TimeZone and is therefore not
-- immutable — Postgres will not index it. The column holds the *branch-local*
-- date, which is also the only definition of "the same day" a hospital in
-- Asia/Kolkata would accept.
CREATE UNIQUE INDEX IF NOT EXISTS uq_appointments_patient_doctor_day
  ON clinical.appointments (hospital_id, patient_id, practitioner_key, slot_date)
  WHERE patient_id IS NOT NULL
    AND practitioner_key IS NOT NULL
    AND status IN ('booked', 'confirmed', 'checked_in');

-- OP-001 §6: booking is idempotent. Unique-per-hospital where present, so a
-- retried POST returns the original appointment instead of a second one.
CREATE UNIQUE INDEX IF NOT EXISTS uq_appointments_idempotency
  ON clinical.appointments (hospital_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_op_visits_idempotency
  ON clinical.op_visits (hospital_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

-- ── C.5 queue ───────────────────────────────────────────────────────────────

-- EN-006 §5: "numbers never reused within a day". `issued_at` is in the key
-- only because a unique index on a partitioned table must contain every
-- partitioning column. It does not weaken the rule in practice: `series_date`
-- is set from `issued_at`, so two rows sharing (queue, series_date, token_no)
-- necessarily share a month and therefore a partition.
CREATE UNIQUE INDEX IF NOT EXISTS uq_queue_tokens_number
  ON queue.queue_tokens (queue_id, series_date, token_no, issued_at);

-- EN-006 §3.6: the online allocator may never reach into the offline block.
-- This is the whole reason an offline counter and an online counter cannot
-- collide, so it is a constraint and not a comment in the allocator.
ALTER TABLE queue.queue_token_series
  ADD CONSTRAINT queue_token_series_offline_boundary
  CHECK (last_number < offline_reserved_from AND start_number >= 1);

ALTER TABLE queue.queue_offline_blocks
  ADD CONSTRAINT queue_offline_blocks_range CHECK (range_to >= range_from);
ALTER TABLE queue.queue_offline_blocks
  ADD CONSTRAINT queue_offline_blocks_issued
  CHECK (issued_count >= 0 AND issued_count <= (range_to - range_from + 1));

-- EN-006 §5: "One active token per patient per queue per day (re-issue cancels
-- previous)." This one is NOT a unique index, and the reason is a hard
-- PostgreSQL limitation rather than a choice: a unique index on a partitioned
-- table may not be partial, and the rule only applies to the *active* statuses —
-- a served token from this morning must not block a second visit this
-- afternoon. So the rule is enforced by the token issuer inside the same
-- transaction that locks the `queue_token_series` row it is allocating from,
-- which is a lock it already holds; this index is what makes that check a
-- probe. Stated here rather than left implicit, because an invariant enforced
-- only in code is one a future caller can bypass.
CREATE INDEX IF NOT EXISTS idx_queue_tokens_patient_day
  ON queue.queue_tokens (queue_id, series_date, patient_id, status)
  WHERE patient_id IS NOT NULL;

